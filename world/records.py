"""Typed, attributable evidence projected from the append-only day record.

This is a view of executions, never a summary generated by the mind. Each row
retains an exact source pointer and hash. Appending a day leaves existing IDs
unchanged; correcting a source invalidates its ID. Old day files can be read
without being migrated or saved. A partial view never proves absence.
"""
import hashlib
import json
import re
import copy
from collections import Counter

VERSION = 2
POLICY = ("Records: events attest observations/actions; statements attest only words said, "
          "not their truth; works are drafts, not sent letters. Intentions are plans, "
          "not completed acts. Only executed consumption records or eating actions "
          "attest eating; an offer or a receipt alone does not. "
          "Reading attests exposure, not the truth of its content. "
          "Omitted records prove no absence.")


class RecordBudgetError(ValueError):
    pass


def digest(value):
    raw = json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


def charge_id(owed):
    """Only an explicit identity or a recurring bill's source + due date is canonical.

    An item name, amount and date cannot distinguish two legitimate purchases.
    Never turn semantic similarity or a missing legacy identifier into identity.
    """
    if owed.get("charge_id"):
        return owed["charge_id"]
    if owed.get("cost") and owed.get("since"):
        return "cost:" + owed["cost"] + ":" + owed["since"]
    return None


def location(day, when):
    """Place at a recorded minute, preserving unknown locations during a walk."""
    for seg in day.get("segments", []):
        if seg.get("from", "") <= when < seg.get("to", ""):
            if seg.get("mode") == "walk":
                return seg.get("a") if when == seg.get("from") else None
            return seg.get("at")
    return None


def action_time(day, step):
    """An action at the destination starts after its accepted walking segment."""
    begin, end = step.get("t"), step.get("end")
    decision = step.get("decision") or {}
    for seg in day.get("segments", []):
        if seg.get("from") == begin and seg.get("mode") == "walk":
            if decision.get("action") != "walk":
                return seg.get("to"), end
    return begin, end


def project(day):
    """Return the single day's evidence store without changing any source object.

    Deliberately exclude step.event: that legacy string can include NPC speech.
    Future observations are captured separately by World.situation. Neither
    thoughts, intentions nor literary summaries enter the observation channel.
    """
    date = day.get("date", "unknown-date")
    rows, occurrences = [], Counter()

    def add(kind, collection, index, original, **fields):
        sha = digest(original)
        key = (kind, sha)
        occurrences[key] += 1
        rid = f"{date}:{kind}:{sha[:16]}:{occurrences[key]}"
        rows.append(dict(id=rid, kind=kind, source=dict(collection=collection, index=index, sha256=sha), **fields))

    for i, e in enumerate(day.get("entries", [])):
        k, t = e.get("k"), e.get("t")
        common = dict(time=t, place=e.get("place") or location(day, t or ""))
        if k == "said":
            add("statement", "entries", i, e, speaker=e.get("by") or "Hegel",
                recipient=e.get("to"), words=e.get("text", ""), verified=False, **common)
        elif k == "writing":
            add("work", "entries", i, e, work_id=e.get("work"), title=e.get("title"),
                genre=e.get("kind"), recipient=e.get("to"), text=e.get("text", ""),
                status="draft", sitting=e.get("sitting"), **common)
        elif k == "consumed":
            add("event", "entries", i, e, type="consumption", item=e.get("item"),
                food=e.get("food"), charge_id=e.get("charge_id"),
                execution_source=e.get("source"), **common)
        elif k in ("bag", "income", "expense"):
            cheque = bool(e.get("cheque"))
            add("payment", "entries", i, e, canonical_id=charge_id(e),
                item=e.get("item"), amount=e.get("price", 0) if k == "bag" else e.get("amount", 0),
                direction="in" if k == "income" else "out", settled=not cheque and e.get('settles') is not False,
                medium="cheque" if cheque else "cash", creditor=e.get("to"), payer=e.get('from'), **common)
        elif k in ("world", "file", "wear", "people", "read"):
            # Delivered source text proves exposure, not every proposition in it.
            fields = dict(type=k)
            if k == "read":
                fields.update(title=e.get("title"), source_name=e.get("source"),
                              words=e.get("text", ""), content_verified=False)
            elif k == "wear":
                fields.update(item=e.get("item"), status=e.get("status"), gone=bool(e.get("gone")))
            elif k == "people":
                fields.update(name=e.get("name"), role=e.get("role"))
            else:
                fields.update(text=e.get("text", ""))
            add("event", "entries", i, e, **fields, **common)
            if e.get("owe"):
                o = e["owe"]
                add("payment", "entries", i, e, canonical_id=charge_id(o),
                    item=o.get("item") or o.get("why"), amount=o["amount"],
                    direction="out", settled=False, creditor=o.get("to"),
                    obligation=True, **common)

    plan = day.get("plan") or {}
    for i, item in enumerate(plan.get("items", [])):
        add("event", "plan.items", i, item, type="intention", status="planned",
            time=plan.get("written"), intended_time=item.get("time"), place=None,
            text=item.get("intention", ""))

    for i, step in enumerate(day.get("steps", [])):
        ans = step.get("decision")
        if not isinstance(ans, dict):
            continue
        # This source deliberately omits thought and dialogue. Executed fields,
        # with their actual activity interval, are sufficient evidence for an act.
        begin, end = action_time(day, step)
        route = next((seg for seg in day.get("segments", [])
                      if seg.get("from") == step.get("t") and seg.get("mode") == "walk"), {})
        walking = ans.get("action") == "walk"
        add("event", "steps", i, step, type="action", action=ans.get("action"),
            time=begin, end=end, place=None if walking else ans.get("place"),
            **(dict(origin=route.get("a"), destination=ans.get("place")) if walking else {}))
        for j, observed in enumerate(step.get("observations", [])):
            add("event", "steps.observations", [i, j], observed,
                type="observation", time=step.get("t"), place=step.get("observed_at"), text=observed)

    for i, observed in enumerate(day.get('observations', [])):
        add('event','observations',i,observed,type='observation',time=observed['t'],
            place=observed.get('place'),text=observed['text'])

    # Cash is a snapshot at the close/current horizon, never at every earlier hour.
    st = day.get("state") or {}
    if "imprest" in st:
        snapshot = dict(cash=st["imprest"], through=st.get("until"), complete=bool(day.get("complete")))
        add("event", "state", "imprest", snapshot, type="cash",
            time="24:00" if day.get("complete") else (st.get("until") or "").split("T")[-1][:5] or None,
            amount=st["imprest"], at_close=bool(day.get("complete")), place=None)

    horizon='24:00' if day.get('complete') else (st.get('until') or '').split('T')[-1][:5] or None
    if st.get('place'):
        snapshot=dict(place=st['place'],through=st.get('until'),complete=bool(day.get('complete')))
        add('event','state','place',snapshot,type='location',time=horizon,place=st['place'],
            text='Recorded location at this horizon only; not a past or planned location.')
    for key in ('wearing','wardrobe','bag','file'):
        if key in st:
            snapshot=dict(value=st[key],through=st.get('until'),complete=bool(day.get('complete')))
            add('event','state',key,snapshot,type='inventory',time=horizon,place=None,
                text=f"Recorded {key} at this horizon only: {json.dumps(st[key],ensure_ascii=False)}")
    for i,o in enumerate(st.get('owed',[])):
        add('payment','state.owed',i,o,canonical_id=charge_id(o),item=o.get('item') or o.get('why'),
            amount=o['amount'],direction='out',settled=False,creditor=o.get('to'),
            obligation=True,time=horizon,place=None)

    source = {key: day.get(key) for key in ("entries", "steps", "segments", "observations", "plan", "complete")}
    source["state"] = {k: st.get(k) for k in ('imprest','place','wearing','wardrobe','bag','file','owed')}
    source["through"] = st.get("until")
    return dict(version=VERSION, date=date, source_sha256=digest(source),
                complete=bool(day.get("complete")), steps_present="steps" in day, records=rows)


def refresh(day):
    """Persist the derived view inside the existing day JSON; no second database."""
    store = project(day)
    day["records"] = store
    return store


def resolve(day, record_id):
    """Resolve against the current sources, so stale/corrected IDs cannot be cited."""
    return next((r for r in project(day)["records"] if r["id"] == record_id), None)


def payment_duplicates(store):
    """Report exact canonical replays; distinct purchases are never deduplicated."""
    paid = {}
    duplicates = []
    for r in store["records"]:
        if r["kind"] != "payment" or not r.get("canonical_id") or not r.get("settled"):
            continue
        cid = r["canonical_id"]
        if cid in paid:
            duplicates.append(dict(canonical_id=cid, first=paid[cid], duplicate=r["id"]))
        else:
            paid[cid] = r["id"]
    return duplicates


def line(r):
    """Readable evidence with its kind and ID; text remains attributed."""
    head = f"[{r['kind']} {r['id']}] {r.get('time') or 'time unknown'}"
    if r.get("place"):
        head += " at " + r["place"]
    kind = r["kind"]
    if kind == "statement":
        return head + f": {r['speaker']} said to {r.get('recipient') or 'unknown recipient'}: “{r['words']}” (unverified)."
    if kind == "work":
        return head + f": draft {r.get('genre') or 'work'} “{r.get('title') or ''}” to {r.get('recipient') or 'nobody specified'}; not sent. {r['text']}"
    if kind == "payment":
        state = "settled" if r["settled"] else "unsettled"
        counterparty=('; to '+r['creditor']) if r.get('creditor') else ('; from '+r['payer']) if r.get('payer') else ''
        return head + f": {r['direction']} ₹{r['amount']} {r.get('item') or ''}{counterparty}; {state}; canonical={r.get('canonical_id') or 'unknown'}; {r.get('medium') or 'obligation'}."
    typ = r["type"]
    if typ == "action":
        interval = f"–{r['end']}" if r.get("end") else ""
        if r.get("action") == "walk":
            return head + interval + f": executed walk from {r.get('origin') or 'unknown origin'} to {r.get('destination') or 'unknown destination'}; arrival at interval end."
        return head + interval + f": executed {r['action']}."
    if typ == "cash":
        return head + f": cash ₹{r['amount']} at {'day close' if r['at_close'] else 'current horizon only'}."
    if typ == "consumption":
        return head + f": executed consumption of {r.get('item')}; {r.get('food')}; source={r.get('execution_source')}; charge={r.get('charge_id') or 'none'}; eating occurred."
    if typ == "intention":
        return head + f": intention only, planned for {r.get('intended_time')}: {r.get('text')}; not evidence of execution."
    if typ == "read":
        return head + f": read {r.get('source_name')}, “{r.get('title')}”: “{r['words']}” (source content unverified)."
    if typ == "wear":
        return head + f": {r.get('item')}; {r.get('status')}."
    if typ == "people":
        return head + f": met {r.get('name')}, {r.get('role')} (card, not a witnessed biography)."
    return head + ": " + r.get("text", "")


def critical(r):
    return r["kind"] == "payment" or (r["kind"] == "event" and
           (r.get("type") in ("cash", "read", "wear", "inventory", "consumption", "location") or r.get("action") == "eat"))


def render(store, limit=24000):
    """Keep every critical outcome intact, and at least each other row's identity.

    Fail explicitly if that cannot fit. A long statement/source/work may be
    excerpted but retains its kind and attribution; an excerpt is never evidence
    of a negative claim about the omitted words. The full text stays in the store.
    """
    rows = [(r, re.sub(r"\s+", " ", line(r)).strip()) for r in store["records"]]
    if not rows:
        text = POLICY + "\nNo records available; no inference of absence."
        if len(text) > limit:
            raise RecordBudgetError("Record policy cannot fit in the prompt budget")
        return text
    def fit(cap):
        lines = [POLICY]
        for r, text in rows:
            # Critical source passages retain delivery/title/identity, while their
            # long quoted body can be shortened; quantities/actions are never cut.
            keep = critical(r) and r.get("type") != "read"
            minimum = len(f"[{r['kind']} {r['id']}]") + 85
            n = max(minimum, cap)
            lines.append(text if keep or len(text) <= n else text[:n - 1].rstrip() + "… [excerpt]")
        return "\n".join(lines)
    lo, hi = 0, max(len(t) for _, t in rows)
    if len(fit(lo)) > limit:
        raise RecordBudgetError(f"{len(rows)} records cannot retain critical outcomes and identities in {limit} characters")
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if len(fit(mid)) <= limit:
            lo = mid
        else:
            hi = mid - 1
    return fit(lo)


COMPACT_CHARS = 9000      # the compact view stays well under the prompt the writers had before typed records
COMPACT_HEAD = ("What happened today, from the record. Facts happened. Payments are as booked. Said: only the words "
                "someone spoke, not facts. Plans: intentions, not acts. Drafts: written, not sent. What is not listed is "
                "unknown, not absent.")


def compact_line(r):
    """One plain line for a writer, without the record id: when, where, what. (section, text)."""
    t = r.get("time") or "?"
    at = f" at {r['place']}" if r.get("place") else ""
    kind = r["kind"]
    if kind == "statement":
        return "said", f"{t}{at} {r.get('speaker') or 'someone'} to {r.get('recipient') or 'someone'}: “{r.get('words', '')}”"
    if kind == "work":
        return "drafts", f"{t} {r.get('genre') or 'work'} “{r.get('title') or ''}” to {r.get('recipient') or 'nobody named'}"
    if kind == "payment":
        who = f" to {r['creditor']}" if r.get("creditor") else f" from {r['payer']}" if r.get("payer") else ""
        state = ("received" if r.get('settled') else "cheque received, not cashed") if r.get("direction") == "in" else "paid" if r.get("settled") else "owed, not paid"
        return "payments", f"{t} ₹{r.get('amount')} {r.get('item') or ''}{who}: {state}" + (" (a cheque)" if r.get("medium") == "cheque" else "")
    typ = r.get("type")
    if typ == "intention":
        return "plans", f"planned for {r.get('intended_time') or '?'}: {r.get('text', '')}"
    if typ == "action":
        span = f"{t}–{r['end']}" if r.get("end") else t
        if r.get("action") == "walk":
            return "facts", f"{span} walked from {r.get('origin') or '?'} to {r.get('destination') or '?'}"
        return "facts", f"{span} {r.get('action')}{at}"
    if typ == "consumption":
        return "facts", f"{t}{at} ate {r.get('item')}" + (f" ({r['food']})" if r.get("food") else "")
    if typ == "cash":
        return "facts", f"cash {'at the close of the day' if r.get('at_close') else 'at ' + t}: ₹{r.get('amount')}"
    if typ == "read":
        return "facts", f"{t} read “{r.get('title') or ''}” ({r.get('source_name') or 'a source'})"
    if typ == "wear":
        return "facts", f"{t} {r.get('item')}: {r.get('status')}"
    if typ == "people":
        return "facts", f"{t} met {r.get('name')}, {r.get('role')}"
    if typ == "location":
        return "facts", f"{t} he is at {r.get('place')}"
    return "facts", f"{t}{at} {r.get('text', '')}"


def compact(store, query='', limit=COMPACT_CHARS):
    """The day's records grouped for a writer: facts, payments, what was said (not verified), plans (not done) and
    drafts (not sent), without record ids or provenance, so the evidence costs a fraction of the full view.

    Nothing is summarised or invented: every line comes from one record. Facts and payments are never cut. When the
    view is too long, quoted words and long observations are shortened first, then the oldest observations and
    earlier days' lines are left out, and the view says so. RecordBudgetError if even the facts and payments do not fit.
    """
    today = store["date"] + ":"
    order = ("facts", "payments", "said", "plans", "drafts")
    titles = {"facts": "Facts:", "payments": "Payments:", "said": "Said (not verified):",
              "plans": "Plans (intentions, not done):", "drafts": "Drafts (not sent):"}
    rows = sorted(store["records"], key=lambda r: (r["id"][:10], r.get("time") or "", r["id"]))
    lines = []                                   # (section, text, kept: never shortened or dropped, earlier day)
    for r in rows:
        section, text = compact_line(r)
        text = re.sub(r"\s+", " ", text).strip()
        firm = section == "payments" or (section == "facts" and r.get("type") in ("action", "consumption", "cash", "location", "wear"))
        old = not r['id'].startswith(today)
        lines.append((section, (r['id'][:10] + ' ' + text) if old else text, firm, old))
    tokens = set(re.findall(r"\w{4,}", query.casefold()))
    earlier = [x for x in lines if x[3]]
    earlier.sort(key=lambda x: len(tokens & set(re.findall(r"\w{4,}", x[1].casefold()))), reverse=True)
    lines = [x for x in lines if not x[3]] + [x for x in earlier[:6] if tokens & set(re.findall(r"\w{4,}", x[1].casefold()))]

    def build(chosen, cap):
        out, dropped = [COMPACT_HEAD], len(lines) - len(chosen)
        for section in order:
            body = [(t if firm or len(t) <= cap else t[:cap - 1].rstrip() + "…") for s, t, firm, _ in chosen if s == section]
            if body:
                out.append(titles[section] + "\n" + "\n".join(body))
        if dropped:
            out.append(f"[{dropped} earlier lines left out; leaving out proves nothing.]")
        return "\n\n".join(out)

    chosen = list(lines)
    floor = 60
    if len(build(chosen, floor)) > limit:
        firm_only = [x for x in chosen if x[2]]
        loose = [x for x in chosen if not x[2]]
        while loose and len(build(firm_only + loose, floor)) > limit:
            loose.pop(0)                         # the oldest observation or quotation goes first
        chosen = [x for x in lines if x in firm_only or x in loose]
        if len(build(chosen, floor)) > limit:
            raise RecordBudgetError(f"{len(firm_only)} facts and payments cannot fit in {limit} characters")
    lo, hi = floor, max([len(x[1]) for x in chosen] + [floor])
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if len(build(chosen, mid)) <= limit:
            lo = mid
        else:
            hi = mid - 1
    return build(chosen, lo)


def relevant(store, query='', limit=24000, view='full'):
    """Budgeted projection, never a generated summary or a change to stored facts.

    Critical outcomes have reserved room. Omitted rows remain in the daily store;
    the prompt explicitly warns that a selected view is not an exhaustive log.
    """
    if view == 'compact':
        return compact(store, query, min(limit, COMPACT_CHARS))
    rows=store['records']
    today=lambda r:r['id'].startswith(store['date']+':')
    if limit>=12000:
        chosen=[r for r in rows if today(r) and critical(r)]
    else:
        chosen=[r for r in rows if today(r) and r['kind']=='event' and
                (r.get('type') in ('cash','consumption','location') or r.get('action')=='eat')]
    tokens=set(re.findall(r'\w{4,}',query.casefold()))
    selected={r['id'] for r in chosen}
    others=[r for r in rows if r['id'] not in selected]
    others.sort(key=lambda r:(today(r),critical(r),len(tokens & set(re.findall(r'\w{4,}',line(r).casefold()))),r.get('time') or ''),reverse=True)
    notice='\n[Selected records; omissions do not establish absence.]'
    render(dict(store,records=chosen),limit-len(notice))
    for r in others:
        try:
            render(dict(store,records=chosen+[r]),limit-len(notice))
        except RecordBudgetError:
            continue
        chosen.append(r)
    chosen.sort(key=lambda r:(r['id'][:10],r.get('time') or '',r['id']))
    return render(dict(store,records=chosen),limit-len(notice))+notice


def current(day, sit, ctx):
    """A pre-action evidence view; it cannot see the decision's future outcome."""
    view=copy.deepcopy(day)
    stamp=sit['time']
    view.setdefault('entries',[]).extend(dict(e,t=stamp,place=sit['place']) for e in ctx.get('public',[]))
    observed=[]
    observed.append(dict(t=stamp,place=sit['place'],text=
        f"Current location: {sit['place']}. People present now: {', '.join(sit.get('present', [])) or 'nobody'}."))
    weather=f"Weather: {sit['weather']}. Air quality index: {sit['aqi']}."
    if weather not in ctx.get('observations',[]):
        observed.append(dict(t=stamp,place=sit['place'],text=weather))
    observed.extend(dict(t=stamp,place=ctx.get('observed_at',sit['place']),text=x) for x in ctx.get('observations',[]))
    view.setdefault('observations',[]).extend(observed)
    greeting=ctx.get('greeting')
    if greeting:
        view['entries'].append(dict(k='said',t=stamp,place=sit['place'],by=greeting['by'],to='Hegel',text=greeting['says']))
    return project(view)


def recall(store, query='', limit=850, lines=8, width=220):
    """Replace the old recall block within its character and line budgets."""
    tokens=set(re.findall(r'\w{4,}',query.casefold()))
    rows=sorted(store['records'],key=lambda r:(
        len(tokens & set(re.findall(r'\w{4,}',line(r).casefold()))),
        r['id'][:10],critical(r),r.get('time') or ''),reverse=True)
    out=[];used=0
    for r in rows:
        text=re.sub(r'\s+',' ',line(r))
        if len(text)>width:
            text=text[:width-12].rsplit(' ',1)[0]+'… [excerpt]'
        if used+len(text)+3>limit:
            continue
        out.append(text);used+=len(text)+3
        if len(out)==lines:
            break
    return list(reversed(out))
