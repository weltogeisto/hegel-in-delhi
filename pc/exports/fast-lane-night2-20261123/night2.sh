#!/bin/bash
# The fast lane, night 2 (pc/FAST-LANE-NIGHT2.md, W12; DECISIONS 61, 62): two futures of his, simulate --days 60 from Day 55's
# saved morning (shadow at "Day 55 begins"), seeds 1831 and 2718 side by side on the live server (never restarted). No new day
# after 07:30; both stopped at 07:45, the complete days stand. Night 1's GPU rule. Push to codex/fast-lane-night2-20261123, post DONE.
SP=/c/Users/hendr/AppData/Local/Temp/claude/cd74254ce8d0a965/90b4347d-b5da-4fc9-99db-4ff38302b710/scratchpad
WSP=/mnt/c/Users/hendr/AppData/Local/Temp/claude/cd74254ce8d0a965/90b4347d-b5da-4fc9-99db-4ff38302b710/scratchpad
SPW='C:/Users/hendr/AppData/Local/Temp/claude/cd74254ce8d0a965/90b4347d-b5da-4fc9-99db-4ff38302b710/scratchpad'
export MSYS_NO_PATHCONV=1
PI="ssh -o BatchMode=yes -o ConnectTimeout=15 -o IdentitiesOnly=yes -i $HOME/.ssh/gondolin_key faqts@Gondolin.local"
REPO=/c/AI/projects/hegel-in-delhi
BRANCH=codex/fast-lane-night2-20261123
DEST=pc/exports/fast-lane-night2-20261123
BR=$SP/night2-branch
WDEST=$WSP/night2-branch/$DEST
LOG=$SP/night2.log
DONEF=$SP/night2-done.txt
SEEDS=(1831 2718)
MODEL_SHA=322e194ff79741c7baa497c240f677f54b201b0efab44ca8e50f122b39123482
TESTED_DIGEST=38bf588439f1f1d133376360fc9ad5f457db1c49dda4393b8f3b3cbb888caad9
log() { echo "[$(date +%FT%T)] $*" | tee -a "$LOG"; }
hhmm() { echo $((10#$(date +%H%M))); }
morning_side() { [ "$(hhmm)" -lt 2100 ]; }                     # after midnight, before the evening
W() { wsl.exe -d Ubuntu-24.04 -- "$@" < /dev/null; }
post() { printf '%s\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n' "$1" > "$SP/night2-post.md"; (cd "$REPO" && gh pr comment 1 --repo weltogeisto/hegel-in-delhi --body-file "$SPW/night2-post.md" 2>&1 | tail -1 | tee -a "$LOG"); }
up() { [ "$(curl -s -m 10 -o /dev/null -w '%{http_code}' http://127.0.0.1:8082/health)" = 200 ]; }
check8082() {  # 3 tries over a minute; if still down, the Windows starter once (the only way the live server is started)
  for t in 1 2 3; do up && { log "8082 answers ($1)"; return 0; }; sleep 20; done
  log "8082 does not answer ($1): the Windows starter"
  powershell.exe -NoProfile -ExecutionPolicy Bypass -File 'C:\hegel\scripts\Start-HegelQwen8082.ps1' >> "$LOG" 2>&1
  sleep 120; up && { log "8082 answers after the Windows starter"; return 2; }
  log "8082 still down"; return 1
}
maxsecs() { python -c "
import datetime as d
n=d.datetime.now(); s=n.replace(hour=7,minute=50,second=0,microsecond=0)
s = s if n < s else s + d.timedelta(days=1)
print(int((s-n).total_seconds()))"; }
ndays() { W bash -c "ls /home/ai/night2/futures/$1/days/ 2>/dev/null | grep -c '^2026-'" | tr -dc 0-9; }
running() { ! grep -q "^$1 " "$DONEF" 2>/dev/null; }
stop_future() {  # SEED WHY
  running $1 || return 0
  grep -q "^$1 " "$SP/night2-stopped.txt" 2>/dev/null || echo "$1 $2" >> "$SP/night2-stopped.txt"
  log "stop $1: $2"; W pkill -TERM -f "night2_run.py.$1" >/dev/null 2>&1
}
finish_all() {  # WHAT: complete days, health rows, RUN.json of each future into the branch, then commit and push
  local s how
  for s in "${SEEDS[@]}"; do
    how=$(grep "^$s " "$SP/night2-stopped.txt" 2>/dev/null | head -1 | cut -d' ' -f2-); running $s && how="${how:-still running (an interim copy)}"
    printf '%s' "$how" > "$SP/night2-how-$s.txt"
    W python3 /home/ai/night2/night2_finish.py $s "$WDEST" live "$WSP/night2-how-$s.txt" 2>&1 | tail -1 | tee -a "$LOG" | sed -n 's/^FINISH //p' > "$SP/night2-finish-$s.json"
  done
  cp "$GPULOG" "$BR/$DEST/gpu-log.csv" 2>/dev/null; cp "$LOG" "$BR/$DEST/night2.log"
  W bash -c "cp /home/ai/night2/MORNING.json /home/ai/night2/SERVER.json /home/ai/night2/SWITCHES.json /home/ai/night2/ENGINE $WDEST/" 2>>"$LOG"
  cp "$SP"/night2.sh "$SP"/night2_run.py "$SP"/night2_run.sh "$SP"/night2_setup.py "$SP"/night2_finish.py "$BR/$DEST/" 2>/dev/null
  (cd "$BR" && git add $DEST && { git diff --cached --quiet && log "nothing new to commit ($1)" || git -c user.name="Claude on the PC" -c user.email=noreply@anthropic.com commit -q -m "The fast lane, night 2 (W12): $1, unread

pc/FAST-LANE-NIGHT2.md (DECISIONS 61, 62): two futures, simulate --days 60 from Day 55's saved morning (shadow $MCOMMIT),
seeds 1831 and 2718 side by side on the live server (never restarted), every switch as the Pi runs on Day 55, prompt cache off,
phone cache frozen, no feeds. Days complete: $(days_line). Evaluation only; nothing here becomes training data, and nothing
reaches his world.

Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>"; } && git push -q github $BRANCH 2>>"$LOG" && log "pushed $BRANCH $(git rev-parse --short HEAD): $1") || log "commit/push failed: $1"
}
days_line() { local s o=""; for s in "${SEEDS[@]}"; do o="$o${o:+; }$s: $(python -c "import json,sys; d=json.load(open(sys.argv[1])); print(f\"{d['days_complete']} days ({d['first']} to {d['last']})\")" "$SPW/night2-finish-$s.json" 2>/dev/null || echo '?')"; done; echo "$o"; }

# --- the GPU, read only, night 1's rule: 2 at once; 0x20/0x40 more than 30 minutes in a row -> one future (2718 stops, its days
#     stand); 0x40 at all, or the core above 83 C for 10 minutes -> both stop; a sample a minute, every fifth to gpu-log.csv
GPULOG=$SP/night2-gpu-log.csv
GQ=timestamp,temperature.gpu,temperature.memory,power.draw,fan.speed,utilization.gpu,clocks.sm,clocks_throttle_reasons.active
TH20=$SP/night2-th20.txt; GSTOPF=$SP/night2-gpustop; ONEF=$SP/night2-one
gpu_logger() {
  local n=0 hot=0 cont=0 line T R b20 b40
  echo "$GQ" > "$GPULOG"
  while true; do
    line=$(nvidia-smi --query-gpu=$GQ --format=csv,noheader 2>/dev/null | head -1)
    T=$(echo "$line" | cut -d, -f2 | tr -dc 0-9); R=$(echo "$line" | awk -F, '{print $NF}' | tr -d ' \r')
    [ $((n % 5)) = 0 ] && echo "$line" >> "$GPULOG"
    if [ "${T:-0}" -gt 83 ]; then hot=$((hot+1)); else hot=0; fi
    b20=0; b40=0; case "$R" in 0x*) [ $(( R & 0x20 )) -ne 0 ] && b20=1; [ $(( R & 0x40 )) -ne 0 ] && b40=1;; esac
    [ $b20 = 1 ] && echo "$(date +%H:%M)" >> "$TH20"
    if [ $b20 = 1 ] || [ $b40 = 1 ]; then cont=$((cont+1)); else cont=0; fi
    if [ ! -e "$GSTOPF" ] && { [ $b40 = 1 ] || [ $hot -ge 10 ]; }; then
      if [ $b40 = 1 ]; then WHY="0x40 (HW thermal slowdown) appeared"; else WHY="the core was above 83 C for $hot minutes"; fi
      echo "$WHY at $(date +%H:%M)" > "$GSTOPF"; echo "$line" >> "$GPULOG"; log "GPU stop: $WHY: $line"
    fi
    if [ ! -e "$ONEF" ] && [ $cont -gt 30 ]; then
      echo "$(date +%H:%M)" > "$ONEF"; echo "$line" >> "$GPULOG"; log "GPU: 0x20/0x40 set for $cont minutes in a row at 2 futures: one future from now ($line)"
    fi
    n=$((n+1)); sleep 60
  done
}

# --- 1. Day 55's saved morning: shadow at "Day 55 begins" (about 23:45)
log "armed (pid $$)"
until [ "$(hhmm)" -ge 2340 ] || [ "$(hhmm)" -lt 800 ]; do sleep 60; done
while :; do
  C=$($PI 'cd hegel-in-delhi && git log --format=%H -1 --grep="^Day 55 begins$"' 2>/dev/null)
  [ -n "$C" ] && break
  morning_side && [ "$(hhmm)" -ge 130 ] && { log "no 'Day 55 begins' by 01:30"; post "**BLOCKED, the fast lane night 2 (PC seat, $(date +%H:%M) Berlin):** shadow has no \"Day 55 begins\" commit by 01:30, so there is no saved morning for Day 55. Nothing ran."; exit 1; }
  sleep 180
done
MCOMMIT=${C:0:7}; log "Day 55's saved morning: shadow $C"
(cd "$REPO" && GIT_SSH_COMMAND="ssh -o BatchMode=yes -o IdentitiesOnly=yes -i $HOME/.ssh/gondolin_key" git fetch -q origin shadow && git cat-file -e $C) || { log "fetch of $C failed"; post "**BLOCKED, the fast lane night 2 (PC seat, $(date +%H:%M) Berlin):** could not fetch shadow's \"Day 55 begins\" ($MCOMMIT) to the PC. Nothing ran."; exit 1; }
DIGEST=$(cd "$REPO" && git ls-tree $C | grep -v $'\tdocs$' | sha256sum | cut -c1-64)
CODE_NOTE="shadow $MCOMMIT, the code merged at 08:52 (\`307b9cd\`)"; [ "$DIGEST" = "$TESTED_DIGEST" ] || CODE_NOTE="shadow $MCOMMIT (its code differs from 307b9cd's: $DIGEST)"
log "engine: $CODE_NOTE"
(cd "$REPO" && git archive -o "$(cygpath -m "$SP")/night2-engine.tar" $C) || { log "archive failed"; exit 1; }
SET=$(W bash -c "rm -rf /home/ai/night2-dry; python3 $WSP/night2_setup.py $C $MODEL_SHA" 2>&1); log "setup: $SET"
echo "$SET" | grep -q '"pin_matches": true' || { post "**BLOCKED, the fast lane night 2 (PC seat, $(date +%H:%M) Berlin):** the setup did not finish, or the 8082 server is not the pinned one: \`$(echo "$SET" | tail -2 | tr '\n' ' ' | cut -c1-300)\`. Nothing ran."; exit 1; }
check8082 "before the night" ; [ $? = 1 ] && { post "**BLOCKED, the fast lane night 2 (PC seat, $(date +%H:%M) Berlin):** 8082 does not answer, even after the Windows starter. Nothing ran; it needs a human before 08:59."; exit 1; }
sed "s#/home/ai/night1/SERVER.json#/home/ai/night2/SERVER.json#" "$SP/night1_pid.py" > "$SP/night2_pid.py"

# --- 2. the branch
if [ ! -d "$BR" ]; then (cd "$REPO" && git fetch -q github main && git worktree add -q -b $BRANCH "$(cygpath -m "$BR")" github/main) || { log "branch worktree failed"; exit 1; }; fi
mkdir -p "$BR/$DEST"
rm -f "$DONEF" "$GSTOPF" "$ONEF" "$TH20" "$SP/night2-stopped.txt"; touch "$DONEF"
gpu_logger & GPUPID=$!; log "GPU logger started"

# --- 3. the two futures, side by side
T0=$(date +%H:%M)
for s in "${SEEDS[@]}"; do
  ( W bash /home/ai/night2/night2_run.sh $s $(maxsecs) >> "$SP/night2-runs.log" 2>&1; echo "$s $?" >> "$DONEF" ) &
  log "start future $s"
  sleep 20
done
declare -A AT730
LASTCHK=$(date +%s); PUSHED=""
while running ${SEEDS[0]} || running ${SEEDS[1]}; do
  sleep 30
  H=$(hhmm)
  if [ -e "$GSTOPF" ]; then for s in "${SEEDS[@]}"; do stop_future $s "the GPU rule ($(cat "$GSTOPF"))"; done; fi
  [ -e "$ONEF" ] && stop_future 2718 "the GPU rule: 0x20/0x40 over 30 minutes in a row from $(cat "$ONEF"), one future from then"
  if morning_side && [ $H -ge 730 ]; then
    for s in "${SEEDS[@]}"; do
      running $s || continue
      n=$(ndays $s)
      [ -z "${AT730[$s]}" ] && { AT730[$s]=$n; log "07:30: future $s has $n day files; no new day from now"; continue; }
      [ "${n:-0}" -gt "${AT730[$s]}" ] && stop_future $s "07:30: a new day began after 07:30, so it stops there"
    done
  fi
  if morning_side && [ $H -ge 745 ]; then for s in "${SEEDS[@]}"; do stop_future $s "07:45"; done; fi
  if [ $(( $(date +%s) - LASTCHK )) -ge 600 ]; then
    LASTCHK=$(date +%s)
    if ! up; then check8082 "during the night"; c=$?; [ $c = 1 ] && for s in "${SEEDS[@]}"; do stop_future $s "8082 stopped answering"; done; fi
    PS=$(W python3 "$WSP/night2_pid.py" 2>&1); [ "$PS" = SAME ] || log "server check: $PS"
    log "progress: 1831 $(ndays 1831) day files, 2718 $(ndays 2718) day files"
  fi
  for t in 0230 0530; do
    if morning_side && [ $H -ge $((10#$t)) ] && ! echo "$PUSHED" | grep -q $t; then PUSHED="$PUSHED $t"; finish_all "progress at $t"; fi
  done
done
log "both futures have stopped: $(tr '\n' ';' < "$DONEF")"

# --- 4. the end
kill $GPUPID 2>/dev/null
finish_all "the night's end"
GPUSTATS=$(python "$SPW/night1_gpustats.py" "$SPW/night2-gpu-log.csv" 2>&1); log "GPU: $GPUSTATS"
TH="0x20 (SW thermal slowdown) set in $(grep -c . "$TH20" 2>/dev/null || echo 0) one-minute samples"; [ -e "$ONEF" ] && TH="$TH; one future from $(cat "$ONEF")"; [ -e "$GSTOPF" ] && TH="$TH; **stopped by the GPU rule: $(cat "$GSTOPF")**"
sleep 60; check8082 "after the night"; c=$?
LIVE="8082 answers after the night."; [ $c = 2 ] && LIVE="**8082 had stopped answering after the night; the Windows starter brought it back.**"; [ $c = 1 ] && LIVE="**8082 does not answer after the night and the Windows starter did not bring it back: it needs a human before 08:59.**"
STOPS=$(tr '\n' ';' < "$SP/night2-stopped.txt" 2>/dev/null)
HEAD=$(cd "$BR" && git rev-parse --short HEAD)
post "**DONE, the fast lane night 2 (PC seat, $(date +%H:%M) Berlin), unread, on \`$BRANCH\` (\`$HEAD\`):** two futures from Day 55's saved morning ($CODE_NOTE), $T0 to $(date +%H:%M). **Days complete:** $(days_line). How each stopped: ${STOPS:-both ran to their end}. Layout: \`$DEST/futures/<seed>/days/\`, \`health.jsonl\` (a row a day, \`--floor 1\`), \`RUN.json\`, \`log\`, \`slots.txt\`; \`gpu-log.csv\`, \`MORNING.json\`, \`SERVER.json\`, \`SWITCHES.json\`. Live server never restarted. **GPU** (5-min samples): $GPUSTATS; $TH. $LIVE"
log "done"
