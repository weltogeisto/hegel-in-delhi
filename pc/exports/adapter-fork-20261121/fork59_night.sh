#!/bin/bash
# DECISIONS 59: W8's exploratory saved-morning fork, the night of 20 to 21 November (Welt's yes in the PC session, 20 Nov ~23:55).
# Checks -> stop live -> trial server (adapter at scale 0, sha256 checked) -> seeds 1831, 2718, 3141, arms A (decision scale 0) and B (1)
# side by side -> stop trial -> live as it was (pinned argv, no adapter) -> fork_diff + health -> push to a codex/* branch, unread.
# Any failure once the live server is down: restore it first, then post BLOCKED. DONE is posted by hand after a look at the numbers.
SP=/c/Users/hendr/AppData/Local/Temp/claude/cd74254ce8d0a965/90b4347d-b5da-4fc9-99db-4ff38302b710/scratchpad
WSP=/mnt/c/Users/hendr/AppData/Local/Temp/claude/cd74254ce8d0a965/90b4347d-b5da-4fc9-99db-4ff38302b710/scratchpad
WSPW='C:/Users/hendr/AppData/Local/Temp/claude/cd74254ce8d0a965/90b4347d-b5da-4fc9-99db-4ff38302b710/scratchpad'
export MSYS_NO_PATHCONV=1
PI="ssh -o BatchMode=yes -o ConnectTimeout=15 -o IdentitiesOnly=yes -i $HOME/.ssh/gondolin_key faqts@Gondolin.local"
REPO=/c/AI/projects/hegel-in-delhi
BRANCH=codex/adapter-fork-20261121
DEST=pc/exports/adapter-fork-20261121
LOG=$SP/fork59-night.log
log() { echo "[$(date +%FT%T)] $*" | tee -a "$LOG"; }
hhmm() { echo $((10#$(date +%H%M))); }
srv() { wsl.exe -- bash /home/ai/fork59/fork59_server.sh "$@"; }
post() {
  printf '%s\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n' "$1" > "$SP/fork59-post.md"
  (cd "$REPO" && gh pr comment 1 --repo weltogeisto/hegel-in-delhi --body-file "$WSPW/fork59-post.md" 2>&1 | tail -1 | tee -a "$LOG")
}
restore() {
  srv stop-trial >> "$LOG" 2>&1
  for t in 1 2 3; do
    srv start-live >> "$LOG" 2>&1 && { log "live server restored (pinned argv, no adapter)"; return 0; }
    log "start-live attempt $t failed"; sleep 30
  done
  return 1
}
blocked() {  # blocked MESSAGE LIVE_DOWN(0/1)
  local msg=$1
  if [ "$2" = "1" ]; then restore && msg="$msg The live server is restored as it was." || msg="$msg **The live server could NOT be restored: it needs a human before 09:10.**"; fi
  log "BLOCKED: $msg"; post "**BLOCKED, W8's exploratory fork (PC seat, $(date +%H:%M) Berlin):** $msg Log: \`fork59-night.log\` on the PC."
  exit 1
}

log "fork59 driver start"
# 0. Checks: Day 51 complete on the Pi; the Power Guard deadline after 09:30 (read only).
[ "$($PI 'cd hegel-in-delhi && python3 -c "import json,os;d=json.load(open(\"docs/days/2026-11-21.json\"));print(d.get(\"complete\") is True and os.path.exists(\"docs/days/2026-11-22.json\"))"' 2>/dev/null)" = "True" ] \
  || blocked "Day 51 is not marked complete on the Pi; nothing ran, the live server untouched." 0
log "Day 51 complete: $($PI 'cd hegel-in-delhi && git log --oneline -1' 2>&1)"
DL=$(powershell.exe -NoProfile -Command "(Get-ScheduledTaskInfo -TaskName 'PC Power Guard - Deadline').NextRunTime.ToString('yyyy-MM-ddTHH:mm:ss')" | tr -d '\r')
log "Power Guard deadline: $DL"
python -c "import sys,datetime as d;t=d.datetime.fromisoformat(sys.argv[1].strip());sys.exit(0 if t>d.datetime(2026,11,21,9,30) else 1)" "$DL" \
  || blocked "the Power Guard deadline ($DL) is not after 09:30; Welt must Renew. Nothing ran, the live server untouched." 0

# 1. Only at night, with room to be back long before 08:30.
H=$(hhmm); { [ $H -ge 400 ] && [ $H -lt 2130 ]; } && blocked "too late to start (it is $(date +%H:%M)); nothing ran." 0
srv stop-live >> "$LOG" 2>&1 || blocked "the live server would not stop cleanly; nothing ran." 1
log "live server stopped"
srv start-trial >> "$LOG" 2>&1 || blocked "the trial server did not start (adapter check or health); no call made." 1
log "trial server up: $(tail -3 "$LOG" | head -1)"

# 2. The arms: per seed, A and B side by side (two slots, the same conditions); seeds in turn; no new seed after 05:30.
DONE_SEEDS=""
for S in 1831 2718 3141; do
  H=$(hhmm); { [ $H -ge 530 ] && [ $H -lt 2130 ]; } && { log "05:30 reached: seed $S and after not started"; break; }
  log "seed $S: A and B start"
  wsl.exe -- bash -c "cd /home/ai/fork59 && mkdir -p logs && (python3 fork59_arm.py A $S > logs/seed$S-A.log 2>&1 & pa=\$!; python3 fork59_arm.py B $S > logs/seed$S-B.log 2>&1 & pb=\$!; wait \$pa; ea=\$?; wait \$pb; eb=\$?; echo exit A=\$ea B=\$eb; exit \$((ea+eb)))" >> "$LOG" 2>&1
  rc=$?
  log "seed $S done rc=$rc: $(wsl.exe -- bash -c "tail -1 /home/ai/fork59/logs/seed$S-A.log | cut -c1-80; tail -1 /home/ai/fork59/logs/seed$S-B.log | cut -c1-80" | tr '\n' ' ')"
  [ $rc = 0 ] && DONE_SEEDS="$DONE_SEEDS $S"
  [ "$(wsl.exe -- bash -c 'curl -s -m 5 -o /dev/null -w %{http_code} http://127.0.0.1:18802/health')" = "200" ] || blocked "the trial server stopped answering during seed $S; seeds done:${DONE_SEEDS:- none}." 1
done

# 3. The live server as it was.
restore || blocked "the runs ended (seeds done:${DONE_SEEDS:- none}), but" 1
log "live server back; seeds done:$DONE_SEEDS"

# 4. fork_diff per seed and the health rows (on the PC, into the run folder).
wsl.exe -- bash -c "cd /home/ai/fork59 && rm -rf report && mkdir report && for S in 1831 2718 3141; do
  [ -d runs/seed\$S-A ] && [ -d runs/seed\$S-B ] || continue
  python3 engine/tools/fork_diff.py runs/seed\$S-A runs/seed\$S-B > report/fork_diff-seed\$S.txt; python3 engine/tools/fork_diff.py runs/seed\$S-A runs/seed\$S-B --json > report/fork_diff-seed\$S.json
  for A in A B; do (cd engine && python3 -m world report --health --docs ../runs/seed\$S-\$A 2026-11-21) > report/health-seed\$S-\$A.txt 2>&1; done
done; ls report" >> "$LOG" 2>&1

# 5. Push the runs (days, FORK-RUN.json, logs, report, scripts) to the branch, unread. state/draws stays on the PC.
cd "$REPO" && git fetch -q github main && rm -rf "$SP/fork59-branch" && git worktree prune && git worktree add -q -B $BRANCH "$WSPW/fork59-branch" github/main \
  || { log "could not make the branch worktree"; exit 2; }
wsl.exe -- bash -c "set -e; D=$WSP/fork59-branch/$DEST; mkdir -p \$D/runs; cd /home/ai/fork59
  for r in runs/*/; do n=\$(basename \$r); mkdir -p \$D/runs/\$n; cp -r \$r/days \$r/FORK-RUN.json \$D/runs/\$n/; [ -f \$r/index.html ] && cp \$r/index.html \$D/runs/\$n/ || true; done
  cp -r report logs \$D/; cp fork59_arm.py fork59_server.sh ENGINE MORNING \$D/; cp $WSP/fork59_night.sh \$D/; cp $WSP/fork59-night.log \$D/ || true
  du -sh \$D" >> "$LOG" 2>&1
cd "$SP/fork59-branch" && git add $DEST && git commit -q -m "W8's exploratory saved-morning fork (DECISIONS 59): seeds 1831, 2718, 3141, arms A and B, unread

The saved morning of FORK-STANDIN.json (shadow 7dfd9bb, Days 1-50); Day 51 (2026-11-21) once per arm and seed with main 0f6b71e's
engine and every switch the Pi runs. A: HEGEL_DECISION_ADAPTER_SCALE=0, B: =1; voice and writing scales empty. Trial server: the plain
model with --lora-scaled adapter-f16.gguf:0 (sha256 5bd5520f...cbfd, as the Training 1 manifest) on 127.0.0.1:18802; the phone cache
frozen (none in the saved morning; no fetch, the same misses in both arms); no feeds; prompt cache off. Exploratory, never a pass.

Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>" && git push -q github $BRANCH 2>>"$LOG" && log "pushed $BRANCH $(git rev-parse --short HEAD)" || { log "push failed"; exit 3; }
log "fork59 driver finished; DONE to be posted"
