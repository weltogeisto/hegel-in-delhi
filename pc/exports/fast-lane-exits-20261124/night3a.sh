#!/bin/bash
# Tonight's money futures (Welt's word, 24 Nov ~22:15: use the free slots): HEGEL_EXITS off and on side by side, simulate --days 14
# from Day 55's saved morning (shadow faa17f7, as night 2) with main's engine (4c1fdc0d); seeds 1831, 2718, 4242 in turn while the
# night allows. Live server never restarted; prompt cache off, phone cache frozen, no feeds, no network. No new day after 07:30,
# all stopped at 07:45. GPU: 0x40, or the core above 83 C for 10 min, or 0x20/0x40 30 min in a row -> the futures stop, days stand.
export MSYS_NO_PATHCONV=1
SP=/c/Users/hendr/AppData/Local/Temp/claude/cd74254ce8d0a965/90b4347d-b5da-4fc9-99db-4ff38302b710/scratchpad
WSP=/mnt/c/Users/hendr/AppData/Local/Temp/claude/cd74254ce8d0a965/90b4347d-b5da-4fc9-99db-4ff38302b710/scratchpad
SPW='C:/Users/hendr/AppData/Local/Temp/claude/cd74254ce8d0a965/90b4347d-b5da-4fc9-99db-4ff38302b710/scratchpad'
REPO=/c/AI/projects/hegel-in-delhi; BRANCH=codex/fast-lane-exits-20261124; DEST=pc/exports/fast-lane-exits-20261124
BR=$SP/night3a-branch; WDEST=$WSP/night3a-branch/$DEST; LOG=$SP/night3a.log; DONEF=$SP/night3a-done.txt; STOPF=$SP/night3a-stopped.txt
STARTF=$SP/night3a-started.txt
SEEDS=(1831 2718 4242); ARMS=(off on)
W() { wsl.exe -d Ubuntu-24.04 -u ai -- "$@" < /dev/null; }
log() { echo "[$(date +%FT%T)] $*" | tee -a "$LOG"; }
hhmm() { echo $((10#$(date +%H%M))); }
morning_side() { [ "$(hhmm)" -lt 2000 ]; }
post() { printf '%s\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n' "$1" > "$SP/night3a-post.md"; (cd "$REPO" && gh pr comment 1 --repo weltogeisto/hegel-in-delhi --body-file "$SPW/night3a-post.md" 2>&1 | tail -1 | tee -a "$LOG"); }
up() { [ "$(curl -s -m 10 -o /dev/null -w '%{http_code}' http://127.0.0.1:8082/health)" = 200 ]; }
check8082() {
  for t in 1 2 3; do up && return 0; sleep 20; done
  log "8082 does not answer ($1): the Windows starter"
  powershell.exe -NoProfile -ExecutionPolicy Bypass -File 'C:\hegel\scripts\Start-HegelQwen8082.ps1' >> "$LOG" 2>&1
  sleep 120; up && { log "8082 answers after the Windows starter"; return 2; }; log "8082 still down"; return 1; }
maxsecs() { python -c "
import datetime as d
n=d.datetime.now(); s=n.replace(hour=7,minute=50,second=0,microsecond=0)
s = s if n < s else s + d.timedelta(days=1)
print(int((s-n).total_seconds()))"; }
ndays() { W ls /home/ai/night3a/$1/futures/$2/days/ 2>/dev/null | grep -c '^2026-'; }
running() { grep -q "^start $1-$2$" "$STARTF" 2>/dev/null && ! grep -q "^$1-$2 " "$DONEF" 2>/dev/null; }
stop_future() {
  running $1 $2 || return 0
  grep -q "^$1-$2 " "$STOPF" 2>/dev/null || echo "$1-$2 $3" >> "$STOPF"
  log "stop $1-$2: $3"; W pkill -TERM -f "night3a/$1/night3a_run.py $2" >/dev/null 2>&1; }
finish_seed() {  # SEED
  local a how
  for a in "${ARMS[@]}"; do
    how=$(grep "^$a-$1 " "$STOPF" 2>/dev/null | head -1 | cut -d' ' -f2-); printf '%s' "$how" > "$SP/night3a-how-$a-$1.txt"
    W env NIGHT2_BASE=/home/ai/night3a/$a NIGHT2_DATE=2026-11-25 python3 /home/ai/night3a/$a/night2_finish.py $1 "$WDEST/$a" live "$WSP/night3a-how-$a-$1.txt" 2>&1 | tail -1 | tee -a "$LOG" | sed -n 's/^FINISH //p' > "$SP/night3a-finish-$a-$1.json"
  done; }
days_line() {
  local s a o=""
  for s in "${SEEDS[@]}"; do for a in "${ARMS[@]}"; do
    [ -s "$SP/night3a-finish-$a-$s.json" ] || continue
    o="$o${o:+; }$s $a: $(python -c "import json,sys; d=json.load(open(sys.argv[1])); print(str(d['days_complete'])+' days ('+str(d['first'])+' to '+str(d['last'])+')')" "$SPW/night3a-finish-$a-$s.json" 2>/dev/null || echo '?')"
  done; done; echo "${o:-none yet}"; }
commit_push() {
  cp "$GPULOG" "$BR/$DEST/gpu-log.csv" 2>/dev/null; cp "$LOG" "$BR/$DEST/night.log"
  for a in "${ARMS[@]}"; do
    mkdir -p "$BR/$DEST/$a"
    for f in MORNING.json SERVER.json SWITCHES.json ENGINE; do W cp /home/ai/night3a/$a/$f $WDEST/$a/$f 2>>"$LOG"; done
  done
  cp "$SP"/night3a.sh "$SP"/night3a_setup.py "$SP"/night3a_run.py "$SP"/night3a_run.sh "$SP"/night2_finish.py "$BR/$DEST/" 2>/dev/null
  (cd "$BR" && git add $DEST && { git diff --cached --quiet || git -c user.name="Claude on the PC" -c user.email=noreply@anthropic.com commit -q -m "Money futures, HEGEL_EXITS off and on (Welt's word of 24 Nov): $1, unread

simulate --days 14 from Day 55's saved morning (shadow faa17f7, as night 2) with main's engine (4c1fdc0d), every switch as
the Pi runs, the on arm with HEGEL_EXITS=1; the live server, never restarted. Days complete: $(days_line).
Evaluation only; nothing here becomes training data, and nothing reaches his world.

Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>"; } && git push -q -u github $BRANCH 2>>"$LOG" && log "pushed $(git rev-parse --short HEAD): $1") || log "commit/push failed: $1"; }

GPULOG=$SP/night3a-gpu.csv; GSTOPF=$SP/night3a-gpustop
gpu_logger() {
  local n=0 hot=0 cont=0 line T R b20 b40
  echo "timestamp,temp,power,util,sm,throttle" > "$GPULOG"
  while :; do
    line=$(nvidia-smi --query-gpu=timestamp,temperature.gpu,power.draw,utilization.gpu,clocks.sm,clocks_throttle_reasons.active --format=csv,noheader 2>/dev/null | head -1)
    T=$(echo "$line" | cut -d, -f2 | tr -dc 0-9); R=$(echo "$line" | awk -F, '{print $NF}' | tr -d ' \r')
    [ $((n % 5)) = 0 ] && echo "$line" >> "$GPULOG"
    if [ "${T:-0}" -gt 83 ]; then hot=$((hot+1)); else hot=0; fi
    b20=0; b40=0; case "$R" in 0x*) [ $(( R & 0x20 )) -ne 0 ] && b20=1; [ $(( R & 0x40 )) -ne 0 ] && b40=1;; esac
    if [ $b20 = 1 ] || [ $b40 = 1 ]; then cont=$((cont+1)); else cont=0; fi
    if [ ! -e "$GSTOPF" ]; then
      [ $b40 = 1 ] && echo "0x40 (HW thermal slowdown) at $(date +%H:%M)" > "$GSTOPF"
      [ $hot -ge 10 ] && echo "the core above 83 C for 10 minutes at $(date +%H:%M)" > "$GSTOPF"
      [ $cont -gt 30 ] && echo "0x20/0x40 for 30 minutes in a row at $(date +%H:%M)" > "$GSTOPF"
      [ -e "$GSTOPF" ] && { echo "$line" >> "$GPULOG"; log "GPU stop: $(cat "$GSTOPF"): $line"; }
    fi
    n=$((n+1)); sleep 60
  done; }

log "armed (pid $$)"; rm -f "$DONEF" "$STOPF" "$GSTOPF" "$STARTF"; touch "$DONEF" "$STARTF"
until ! W pgrep -f "REQUESTS-ceiling-" >/dev/null; do sleep 30; done
log "the ceiling streams are done"
check8082 "before the futures"
if [ $? = 1 ]; then post "**BLOCKED, the money futures (PC seat, $(date +%H:%M) Berlin):** 8082 does not answer, even after the Windows starter. Nothing ran."; exit 1; fi
if [ ! -d "$BR" ]; then (cd "$REPO" && git fetch -q github main && git worktree add -q -b $BRANCH "$(cygpath -m "$BR")" github/main) || { log "branch worktree failed"; exit 1; }; fi
mkdir -p "$BR/$DEST"
gpu_logger & GPUPID=$!; trap 'kill $GPUPID 2>/dev/null' EXIT
T0=$(date +%H:%M)
for s in "${SEEDS[@]}"; do
  [ -e "$GSTOPF" ] && break
  if morning_side && [ $(hhmm) -ge 700 ]; then log "07:00: no new seed"; break; fi
  for a in "${ARMS[@]}"; do
    echo "start $a-$s" >> "$STARTF"
    ( W env NIGHT2_BASE=/home/ai/night3a/$a NIGHT2_DAYS=14 bash /home/ai/night3a/$a/night3a_run.sh $s $(maxsecs) >> "$SP/night3a-runs.log" 2>&1; echo "$a-$s $?" >> "$DONEF" ) &
    log "start $a $s"; sleep 20
  done
  unset AT730; declare -A AT730; LASTCHK=$(date +%s)
  while running off $s || running on $s; do
    sleep 30; H=$(hhmm)
    if [ -e "$GSTOPF" ]; then for a in "${ARMS[@]}"; do stop_future $a $s "the GPU rule ($(cat "$GSTOPF"))"; done; fi
    if morning_side && [ $H -ge 730 ]; then
      for a in "${ARMS[@]}"; do
        running $a $s || continue
        n=$(ndays $a $s)
        if [ -z "${AT730[$a]}" ]; then AT730[$a]=$n; log "07:30: $a $s has $n day files; no new day from now"; continue; fi
        [ "${n:-0}" -gt "${AT730[$a]}" ] && stop_future $a $s "07:30: a new day began after 07:30"
      done
    fi
    if morning_side && [ $H -ge 745 ]; then for a in "${ARMS[@]}"; do stop_future $a $s "07:45"; done; fi
    if [ $(( $(date +%s) - LASTCHK )) -ge 600 ]; then
      LASTCHK=$(date +%s)
      if ! up; then check8082 "during the night"; [ $? = 1 ] && for a in "${ARMS[@]}"; do stop_future $a $s "8082 stopped answering"; done; fi
      log "progress $s: off $(ndays off $s), on $(ndays on $s) day files"
    fi
  done
  log "seed $s ended: $(grep -- "-$s " "$DONEF" | tr '\n' ';')"
  finish_seed $s; commit_push "seed $s done"
done
kill $GPUPID 2>/dev/null
sleep 30; check8082 "after the night"; c=$?
LIVE="8082 answers after the night."
[ $c = 2 ] && LIVE="**8082 had stopped answering; the Windows starter brought it back.**"
[ $c = 1 ] && LIVE="**8082 does not answer after the night: it needs a human before 08:59.**"
TMAX=$(awk -F', ' 'NR>1{if($2+0>m)m=$2+0} END{print m}' "$GPULOG" 2>/dev/null)
HEAD=$(cd "$BR" && git rev-parse --short HEAD); STOPS=$(tr '\n' ';' < "$STOPF" 2>/dev/null)
GR=""; [ -e "$GSTOPF" ] && GR=" **GPU rule:** $(cat "$GSTOPF")."
post "**DONE, the money futures (PC seat, $(date +%H:%M) Berlin), unread, on \`$BRANCH\` (\`$HEAD\`):** HEGEL_EXITS off and on side by side, \`simulate --days 14\` from Day 55's saved morning (shadow \`faa17f7\`, the same morning as night 2) with main's engine \`4c1fdc0d\`, every switch as the Pi runs; $T0 to $(date +%H:%M), beside W13/W14 on the third slot. **Days complete:** $(days_line). How each stopped: ${STOPS:-all ran to their end}.$GR GPU max ${TMAX} °C. Layout: \`$DEST/{off,on}/futures/<seed>/\` with \`days/\`, \`health.jsonl\`, \`RUN.json\`, \`log\`, \`slots.txt\`; \`gpu-log.csv\`. Live server never restarted. $LIVE For your reading with \`tools/world_score.py --compare\` and \`tools/works_score.py\`, as in \`pc/FAST-LANE-NIGHT3.md\`; Wednesday's own run is unchanged."
log "done"
