#!/bin/bash
# The fast lane, night 3 (W15, pc/FAST-LANE-NIGHT3.md on main f34e42b0): the repaired money packet, HEGEL_EXITS off and on side by
# side, simulate --days 14 from Day 57's saved morning (shadow at "Day 57 begins"), main's engine f34e42b0. Seeds 1831, 2718, then
# 4242; the look-up arm (seed 1831, EXITS + BORROWED_LOOKUP, Wikipedia reachable) once W14 has given its slot back. Live server
# never restarted; prompt cache off, phone cache frozen, no feeds. No new day after 07:30, all stopped at 07:45. Night 1's GPU rule:
# 0x40, or the core above 83 C for 10 min -> all futures stop; 0x20/0x40 30 min in a row -> no new future starts. Also W16 once.
export MSYS_NO_PATHCONV=1
SP=/c/Users/hendr/AppData/Local/Temp/claude/cd74254ce8d0a965/90b4347d-b5da-4fc9-99db-4ff38302b710/scratchpad
WSP=/mnt/c/Users/hendr/AppData/Local/Temp/claude/cd74254ce8d0a965/90b4347d-b5da-4fc9-99db-4ff38302b710/scratchpad
SPW='C:/Users/hendr/AppData/Local/Temp/claude/cd74254ce8d0a965/90b4347d-b5da-4fc9-99db-4ff38302b710/scratchpad'
REPO=/c/AI/projects/hegel-in-delhi; BRANCH=codex/fast-lane-night3-20261125; DEST=pc/exports/fast-lane-night3-20261125
BR=$SP/night3-branch; WDEST=$WSP/night3-branch/$DEST; LOG=$SP/night3.log; DONEF=$SP/night3-done.txt; STOPF=$SP/night3-stopped.txt
STARTF=$SP/night3-started.txt; W14END=$SP/night25-w14-ended
PI="ssh -o BatchMode=yes -o ConnectTimeout=15 -o IdentitiesOnly=yes -i $HOME/.ssh/gondolin_key faqts@Gondolin.local"
MODEL_SHA=322e194ff79741c7baa497c240f677f54b201b0efab44ca8e50f122b39123482
PAIRS=(1831 2718 4242)
W() { wsl.exe -d Ubuntu-24.04 -u ai -- "$@" < /dev/null; }
log() { echo "[$(date +%FT%T)] $*" | tee -a "$LOG"; }
hhmm() { echo $((10#$(date +%H%M))); }
morning_side() { [ "$(hhmm)" -lt 2000 ]; }
post() { local q="$SP/postq/$(date +%Y%m%d-%H%M%S)-$$.md"; printf '%s

---
_Generated by [Claude Code](https://claude.ai/code)_
' "$1" > "$q"; log "queued post $(basename "$q")"; }
up() { [ "$(curl -s -m 10 -o /dev/null -w '%{http_code}' http://127.0.0.1:8082/health)" = 200 ]; }
check8082() {
  for t in 1 2 3; do up && return 0; sleep 20; done
  log "8082 does not answer ($1): the Windows starter"
  powershell.exe -NoProfile -ExecutionPolicy Bypass -File 'C:\hegel\scripts\Start-HegelQwen8082.ps1' >> "$LOG" 2>&1
  sleep 120; up && { log "8082 answers after the Windows starter"; return 2; }; log "8082 still down"; return 1; }
maxsecs() { python -c "
import datetime as d
n=d.datetime.now(); s=n.replace(hour=7,minute=50,second=0,microsecond=0)
s = s if n < s else s + d.timedelta(days=1)
print(int((s-n).total_seconds()))"; }
ndays() { W ls /home/ai/night3/$1/futures/$2/days/ 2>/dev/null | grep -c '^2026-'; }
started() { grep -q "^start $1-$2$" "$STARTF" 2>/dev/null; }
running() { started $1 $2 && ! grep -q "^$1-$2 " "$DONEF" 2>/dev/null; }
stop_future() {
  running $1 $2 || return 0
  grep -q "^$1-$2 " "$STOPF" 2>/dev/null || echo "$1-$2 $3" >> "$STOPF"
  log "stop $1-$2: $3"; W pkill -TERM -f "night3/$1/night3_run.py $2" >/dev/null 2>&1; }
start_future() {  # ARM SEED
  local net=""; [ $1 = lookup ] && net="NIGHT3_NET=wikipedia"
  echo "start $1-$2" >> "$STARTF"
  ( W env NIGHT2_BASE=/home/ai/night3/$1 NIGHT2_DATE=2026-11-27 NIGHT2_DAYS=14 $net bash /home/ai/night3/$1/night3_run.sh $2 $(maxsecs) >> "$SP/night3-runs.log" 2>&1; echo "$1-$2 $?" >> "$DONEF" ) &
  log "start $1 $2"; sleep 20; }
finish_one() {  # ARM SEED
  local how; how=$(grep "^$1-$2 " "$STOPF" 2>/dev/null | head -1 | cut -d' ' -f2-); printf '%s' "$how" > "$SP/night3-how-$1-$2.txt"
  W env NIGHT2_BASE=/home/ai/night3/$1 NIGHT2_DATE=2026-11-27 python3 /home/ai/night3/$1/night2_finish.py $2 "$WDEST/$1" live "$WSP/night3-how-$1-$2.txt" 2>&1 | tail -1 | tee -a "$LOG" | sed -n 's/^FINISH //p' > "$SP/night3-finish-$1-$2.json"; }
days_line() {
  local s a o="" f
  for f in "$SP"/night3-finish-*.json; do
    [ -s "$f" ] || continue; a=$(basename "$f" .json); a=${a#night3-finish-}
    o="$o${o:+; }${a%-*} ${a##*-}: $(python -c "import json,sys; d=json.load(open(sys.argv[1])); print(str(d['days_complete'])+' days ('+str(d['first'])+' to '+str(d['last'])+')')" "$(cygpath -m "$f")" 2>/dev/null || echo '?')"
  done; echo "${o:-none yet}"; }
commit_push() {
  cp "$GPULOG" "$BR/$DEST/gpu-log.csv" 2>/dev/null; cp "$LOG" "$BR/$DEST/night.log"
  for a in off on lookup; do
    mkdir -p "$BR/$DEST/$a"
    for f in MORNING.json SERVER.json SWITCHES.json ENGINE; do W cp /home/ai/night3/$a/$f $WDEST/$a/$f 2>>"$LOG"; done
  done
  cp "$SP"/night3.sh "$SP"/night3_setup.py "$SP"/night3_run.py "$SP"/night3_run.sh "$SP"/night2_finish.py "$BR/$DEST/" 2>/dev/null
  (cd "$BR" && git add $DEST && { git diff --cached --quiet || git -c user.name="Claude on the PC" -c user.email=noreply@anthropic.com commit -q -m "The fast lane, night 3 (W15): $1, unread

pc/FAST-LANE-NIGHT3.md: the repaired packet (main f34e42b0), HEGEL_EXITS off and on side by side, simulate --days 14 from
Day 57's saved morning (shadow $MCOMMIT), every switch as the Pi runs; the look-up arm with HEGEL_BORROWED_LOOKUP. The live
server, never restarted. Days complete: $(days_line). Evaluation only; nothing here becomes training data or reaches his world.

Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>"; } && git push -q -u github $BRANCH 2>>"$LOG" && log "pushed $(git rev-parse --short HEAD): $1") || log "commit/push failed: $1"; }

GPULOG=$SP/night3-gpu.csv; GSTOPF=$SP/night3-gpustop; ONEF=$SP/night3-one
gpu_logger() {
  local n=0 hot=0 cont=0 line T R b20 b40
  echo "timestamp,temp,power,util,sm,throttle" > "$GPULOG"
  while :; do
    line=$(nvidia-smi --query-gpu=timestamp,temperature.gpu,power.draw,utilization.gpu,clocks.sm,clocks_throttle_reasons.active --format=csv,noheader 2>/dev/null | head -1)
    T=$(echo "$line" | cut -d, -f2 | tr -dc 0-9); R=$(echo "$line" | awk -F, '{print $NF}' | tr -d ' \r')
    [ $((n % 5)) = 0 ] && echo "$line" >> "$GPULOG"
    if [ "${T:-0}" -gt 83 ]; then hot=$((hot+1)); else hot=0; fi
    b20=0; b40=0; case "$R" in 0x*) [ $(( R & 0x20 )) -ne 0 ] && b20=1; [ $(( R & 0x40 )) -ne 0 ] && b40=1;; esac
    if [ $b20 = 1 ] || [ $b40 = 1 ]; then cont=$((cont+1)); else cont=0; fi
    if [ ! -e "$GSTOPF" ]; then
      [ $b40 = 1 ] && echo "0x40 (HW thermal slowdown) at $(date +%H:%M)" > "$GSTOPF"
      [ $hot -ge 10 ] && echo "the core above 83 C for 10 minutes at $(date +%H:%M)" > "$GSTOPF"
      [ -e "$GSTOPF" ] && { echo "$line" >> "$GPULOG"; log "GPU stop: $(cat "$GSTOPF"): $line"; }
    fi
    [ ! -e "$ONEF" ] && [ $cont -gt 30 ] && { echo "$(date +%H:%M)" > "$ONEF"; log "GPU: 0x20/0x40 for 30 minutes in a row: no new future from now"; }
    n=$((n+1)); sleep 60
  done; }

# --- 1. Day 57's saved morning
log "armed (pid $$)"; rm -f "$DONEF" "$STOPF" "$GSTOPF" "$ONEF" "$STARTF" "$SP"/night3-finish-*.json; touch "$DONEF" "$STARTF"
while :; do
  C=$($PI 'cd hegel-in-delhi && git log --format=%H -1 --grep="^Day 57 begins$"' 2>/dev/null)
  [ -n "$C" ] && break
  morning_side && [ "$(hhmm)" -ge 130 ] && { log "no 'Day 57 begins' by 01:30"; post "**BLOCKED, the fast lane night 3 (PC seat, $(date +%H:%M) Berlin):** shadow has no \"Day 57 begins\" commit by 01:30, so there is no saved morning for Day 57. Nothing ran."; exit 1; }
  sleep 120
done
MCOMMIT=${C:0:7}; log "Day 57's saved morning: shadow $C"
# W16, once: his day is complete
PAP=$(W bash -c "cd /mnt/c/AI/projects/hw-cards && python3 tools/collect_papers.py --state /home/ai/hegel-eval/papers-archive --body 2>&1 | tail -1" | cut -c1-200); log "W16 papers: $PAP"
(cd "$REPO" && GIT_SSH_COMMAND="ssh -o BatchMode=yes -o IdentitiesOnly=yes -i $HOME/.ssh/gondolin_key" git fetch -q origin shadow && git cat-file -e $C) || { log "fetch of $C failed"; post "**BLOCKED, the fast lane night 3 (PC seat, $(date +%H:%M) Berlin):** could not fetch shadow's \"Day 57 begins\" ($MCOMMIT). Nothing ran."; exit 1; }
(cd "$REPO" && git archive -o "$SPW/night3-morning.tar" $C) || { log "archive failed"; exit 1; }
SET=$(W python3 $WSP/night3_setup.py $C $MODEL_SHA 2>&1); log "setup: $(echo "$SET" | tr '\n' ' ' | cut -c1-600)"
echo "$SET" | grep -q '"pin_matches": true' || { post "**BLOCKED, the fast lane night 3 (PC seat, $(date +%H:%M) Berlin):** the setup did not finish, or 8082 is not the pinned server: \`$(echo "$SET" | tail -2 | tr '\n' ' ' | cut -c1-300)\`. Nothing ran."; exit 1; }
check8082 "before the night"; [ $? = 1 ] && { post "**BLOCKED, the fast lane night 3 (PC seat, $(date +%H:%M) Berlin):** 8082 does not answer, even after the Windows starter. Nothing ran."; exit 1; }
if [ ! -d "$BR" ]; then (cd "$REPO" && git fetch -q github main && git worktree add -q -b $BRANCH "$(cygpath -m "$BR")" github/main) || { log "branch worktree failed"; exit 1; }; fi
mkdir -p "$BR/$DEST"
gpu_logger & GPUPID=$!; trap 'kill $GPUPID 2>/dev/null' EXIT
T0=$(date +%H:%M)

# --- 2. the futures: pairs in turn; the look-up arm when W14 is over
pi=0; PAIR=""; LOOK=no
declare -A AT730
while :; do
  H=$(hhmm); late=no; { morning_side && [ $H -ge 700 ]; } && late=yes
  # start what may start
  if [ -z "$PAIR" ] && [ $pi -lt ${#PAIRS[@]} ] && [ $late = no ] && [ ! -e "$GSTOPF" ] && [ ! -e "$ONEF" ]; then
    PAIR=${PAIRS[$pi]}; pi=$((pi+1)); start_future off $PAIR; start_future on $PAIR
  fi
  if [ $LOOK = no ] && [ -e "$W14END" ] && [ $late = no ] && [ ! -e "$GSTOPF" ] && [ ! -e "$ONEF" ]; then
    LOOK=yes; start_future lookup 1831
  fi
  # the rules for what runs
  for f in ${PAIR:+off-$PAIR on-$PAIR} $( [ $LOOK = yes ] && echo lookup-1831 ); do
    a=${f%-*}; s=${f#*-}; running $a $s || continue
    [ -e "$GSTOPF" ] && stop_future $a $s "the GPU rule ($(cat "$GSTOPF"))"
    if morning_side && [ $H -ge 730 ]; then
      n=$(ndays $a $s)
      if [ -z "${AT730[$f]}" ]; then AT730[$f]=$n; log "07:30: $f has $n day files; no new day from now"
      elif [ "${n:-0}" -gt "${AT730[$f]}" ]; then stop_future $a $s "07:30: a new day began after 07:30"; fi
    fi
    morning_side && [ $H -ge 745 ] && stop_future $a $s "07:45"
  done
  # a pair that has ended: finish both, push
  if [ -n "$PAIR" ] && ! running off $PAIR && ! running on $PAIR; then
    log "seed $PAIR ended: $(grep -- "-$PAIR " "$DONEF" | grep -v lookup | tr '\n' ';')"
    finish_one off $PAIR; finish_one on $PAIR; commit_push "seed $PAIR"; PAIR=""
  fi
  if [ $LOOK = yes ] && ! running lookup 1831 && [ ! -e "$SP/night3-finish-lookup-1831.json" ]; then
    log "the look-up arm ended: $(grep '^lookup-1831 ' "$DONEF")"; finish_one lookup 1831; commit_push "the look-up arm"
  fi
  # the end: nothing runs and nothing more may start
  if [ -z "$PAIR" ] && ! running lookup 1831; then
    more=no
    [ $pi -lt ${#PAIRS[@]} ] && [ $late = no ] && [ ! -e "$GSTOPF" ] && [ ! -e "$ONEF" ] && more=yes
    [ $LOOK = no ] && [ $late = no ] && [ ! -e "$GSTOPF" ] && [ ! -e "$ONEF" ] && more=yes
    [ $more = no ] && break
  fi
  if [ $(( $(date +%s) - ${LASTCHK:-0} )) -ge 600 ]; then
    LASTCHK=$(date +%s)
    if ! up; then check8082 "during the night"; [ $? = 1 ] && for f in off-$PAIR on-$PAIR lookup-1831; do stop_future ${f%-*} ${f#*-} "8082 stopped answering"; done; fi
    log "progress: ${PAIR:+$PAIR off $(ndays off $PAIR), on $(ndays on $PAIR)}$( [ $LOOK = yes ] && echo "; lookup $(ndays lookup 1831)") day files"
  fi
  sleep 30
done

# --- 3. the end
kill $GPUPID 2>/dev/null
sleep 30; check8082 "after the night"; c=$?
LIVE="8082 answers after the night."
[ $c = 2 ] && LIVE="**8082 had stopped answering; the Windows starter brought it back.**"
[ $c = 1 ] && LIVE="**8082 does not answer after the night: it needs a human before 08:59.**"
TMAX=$(awk -F', ' 'NR>1{if($2+0>m)m=$2+0} END{print m}' "$GPULOG" 2>/dev/null)
HEAD=$(cd "$BR" && git rev-parse --short HEAD); STOPS=$(tr '\n' ';' < "$STOPF" 2>/dev/null)
GR=""; [ -e "$GSTOPF" ] && GR=" **GPU rule:** $(cat "$GSTOPF")."; [ -e "$ONEF" ] && GR="$GR No new future after $(cat "$ONEF") (0x20/0x40 for 30 minutes in a row)."
LK="The look-up arm did not start (W14 kept the slot all night)."; [ $LOOK = yes ] && LK="The look-up arm ran with Wikipedia reachable from the PC, as from the Pi."
post "**DONE, W15 the fast lane night 3 (PC seat, $(date +%H:%M) Berlin), unread, on \`$BRANCH\` (\`$HEAD\`):** the repaired packet (main \`f34e42b0\`), off and on side by side, \`simulate --days 14\` from Day 57's saved morning (shadow \`$MCOMMIT\`), every switch as the Pi runs; $T0 to $(date +%H:%M), beside W14. **Days complete:** $(days_line). How each stopped: ${STOPS:-all ran to their end}. $LK$GR GPU max ${TMAX} °C. Layout: \`$DEST/{off,on,lookup}/futures/<seed>/\` with \`days/\`, \`health.jsonl\`, \`RUN.json\`, \`log\`, \`slots.txt\`; \`gpu-log.csv\`. Live server never restarted. $LIVE W16: $PAP"
log "done"
