#!/bin/bash
# W8, the night of 19 to 20 November (pc/TASKS.md W8, pc/LORA-FRESH-SCENES.md), on Welt's yes in chat at 21:16.
# Wait for Day 50 complete -> freeze, commit, push the plan -> stop live -> trial server (adapter at scale 0, sha256 checked)
# -> run --limit 2, then all -> stop trial -> live as it was -> push the folder -> DONE on PR #1. Any failure after the live
# server stops: restore the live server first, then post BLOCKED. Nobody reads the outputs.
SP=/c/Users/hendr/AppData/Local/Temp/claude/b52770502021644c/ae932ed3-101c-49e5-8ebb-b1be766eff5b/scratchpad
WSP=/mnt/c/Users/hendr/AppData/Local/Temp/claude/b52770502021644c/ae932ed3-101c-49e5-8ebb-b1be766eff5b/scratchpad
WSPW='C:/Users/hendr/AppData/Local/Temp/claude/b52770502021644c/ae932ed3-101c-49e5-8ebb-b1be766eff5b/scratchpad'
export MSYS_NO_PATHCONV=1
PI="ssh -o BatchMode=yes -o ConnectTimeout=15 -o IdentitiesOnly=yes -i $HOME/.ssh/gondolin_key faqts@Gondolin.local"
BRANCH=codex/lora-fresh-scenes-20261119
DEST=pc/exports/lora-fresh-scenes-20261119
log() { echo "[$(date +%FT%T)] $*" | tee -a "$SP/w8-night.log"; }
hhmm() { echo $((10#$(date +%H%M))); }
wsl() { wsl.exe -- bash "$WSP/$1" "${@:2}"; }
post() {  # post FILE-BODY-TEXT on PR #1
  printf '%s\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n' "$1" > "$SP/w8-post.md"
  (cd "$SP/pr1-merge" && gh pr comment 1 --repo weltogeisto/hegel-in-delhi --body-file "$SP/w8-post.md" 2>&1 | tail -1 | tee -a "$SP/w8-night.log")
}
restore() {  # stop the trial, start the live server as it was; twice if needed
  wsl w8_server.sh stop-trial >> "$SP/w8-night.log" 2>&1
  for t in 1 2; do
    wsl w8_server.sh start-live >> "$SP/w8-night.log" 2>&1 && { log "live server restored"; return 0; }
    log "start-live attempt $t failed"; sleep 20
  done
  return 1
}
blocked() {  # blocked MESSAGE LIVE_DOWN(0/1)
  local msg=$1
  if [ "$2" = "1" ]; then restore && msg="$msg The live server is restored." || msg="$msg **The live server could NOT be restored: it needs a human before 09:10.**"; fi
  log "BLOCKED: $msg"; post "**BLOCKED W8 (PC seat, $(date +%H:%M) Berlin):** $msg Log: \`w8-night.log\` on the PC."
  exit 1
}

log "W8 driver start"
# 1. Day 50 complete, on the Pi and on GitHub's shadow (the freeze reads origin/shadow).
until [ "$($PI 'cd hegel-in-delhi && python3 -c "import json,os;d=json.load(open(\"docs/days/2026-11-20.json\"));print(d.get(\"complete\") is True and os.path.exists(\"docs/days/2026-11-21.json\"))"' 2>/dev/null)" = "True" ]; do
  H=$(hhmm); [ $H -ge 300 ] && [ $H -lt 1200 ] && blocked "Day 50 was not marked complete by 03:00; nothing ran, the live server untouched." 0
  sleep 120
done
log "Day 50 complete on the Pi: $($PI 'cd hegel-in-delhi && git log --oneline -1' 2>&1)"
for i in $(seq 1 30); do
  (cd "$SP/pr1-merge" && git fetch -q github && git show github/shadow:docs/days/2026-11-20.json 2>/dev/null | python -c "import sys,json;sys.exit(0 if json.load(sys.stdin).get('complete') is True else 1)") && break
  sleep 60
done
log "github shadow: $(cd "$SP/pr1-merge" && git log --oneline -1 github/shadow)"

# 2. Freeze, commit and push the plan before any call.
wsl w8_run.sh freeze >> "$SP/w8-night.log" 2>&1 || blocked "the freeze refused (see log); days and seed unchanged, nothing ran." 0
rm -rf "$SP/w8-export" && mkdir -p "$SP/w8-export"
wsl.exe -- bash -c "cp ~/w8/run/plan.json $WSP/w8-export/plan.json"
PLAN_SHA=$(python -c "import json;print(json.load(open(r'$WSPW/w8-export/plan.json'))['sha256'])")
cd "$SP/pr1-merge" && git fetch -q github && rm -rf "$SP/w8-branch" && git worktree prune && git worktree add -q -B $BRANCH "$WSPW/w8-branch" github/main || blocked "could not make the branch worktree; nothing ran." 0
cd "$SP/w8-branch" && mkdir -p $DEST && cp "$SP/w8-export/plan.json" $DEST/plan.json && git add $DEST && git commit -q -m "W8: the plan, frozen before any call (Days 44-49, seed 1831; plan sha256 $PLAN_SHA)

Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>" && git push -q github $BRANCH 2>>"$SP/w8-night.log" || blocked "the plan could not be committed or pushed; nothing ran." 0
log "plan pushed: $(git rev-parse --short HEAD), plan sha256 $PLAN_SHA"

# 3. Only while he sleeps, and with time to be back by 08:30.
H=$(hhmm); { [ $H -ge 600 ] && [ $H -lt 2130 ]; } && blocked "too late to start before 06:00 (it is $(date +%H:%M)); the plan is pushed, nothing else ran." 0
wsl w8_server.sh stop-live >> "$SP/w8-night.log" 2>&1 || blocked "the live server would not stop cleanly; nothing ran." 1
log "live server stopped"
wsl w8_server.sh start-trial >> "$SP/w8-night.log" 2>&1 || blocked "the trial server did not start (adapter check or health); no call made." 1
log "trial server up"

# 4. Rehearsal, then the whole run.
wsl w8_run.sh run 2 >> "$SP/w8-night.log" 2>&1 || blocked "the rehearsal (--limit 2) failed." 1
log "rehearsal done"
wsl w8_run.sh run >> "$SP/w8-night.log" 2>&1 || blocked "the run failed part way; outputs so far are kept and resumable." 1
RUN=$(wsl.exe -- bash -c "cat ~/w8/run/RUN.json")
log "run done: $(echo "$RUN" | tr -d '\n' | cut -c1-400)"

# 5. The live server as it was.
restore || blocked "the run is complete, but" 1
log "live server back"

# 6. Push the folder (plan, outputs.jsonl, RUN.json, raw requests), unread.
wsl.exe -- bash -c "rm -rf $WSP/w8-branch/$DEST && mkdir -p $WSP/w8-branch/$DEST && cp -r ~/w8/run/. $WSP/w8-branch/$DEST/ && cp $WSP/w8_night.sh $WSP/w8_server.sh $WSP/w8_run.sh $WSP/w8_refs.sh $WSP/w8-branch/$DEST/ 2>/dev/null; ls $WSP/w8-branch/$DEST | tr '\n' ' '" | tee -a "$SP/w8-night.log"
OUT_SHA=$(python -c "import json;print(json.load(open(r'$WSPW/w8-branch/$DEST/RUN.json'))['outputs_sha256'])")
N_OUT=$(python -c "import json;print(json.load(open(r'$WSPW/w8-branch/$DEST/RUN.json'))['outputs'])")
FB=$(python -c "import json;print(json.load(open(r'$WSPW/w8-branch/$DEST/RUN.json'))['fallbacks'])")
cd "$SP/w8-branch" && git add $DEST && git commit -q -m "W8: the adapter's and the plain rewrites of 72 recent thoughts, unread ($N_OUT outputs; outputs sha256 $OUT_SHA)

Trial server: the plain model with --lora-scaled adapter-f16.gguf:0 (sha256 5bd5520f...cbfd, as the
Training 1 manifest), 127.0.0.1:18802, while the live server was down; the live server restored after.

Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>" && git push -q github $BRANCH 2>>"$SP/w8-night.log" || log "push of the outputs failed"
COMMIT=$(git rev-parse --short HEAD)
post "**DONE W8 (PC seat, $(date +%H:%M) Berlin):** plan sha256 \`$PLAN_SHA\` (Days 44–49, seed 1831, pushed before any call); outputs sha256 \`$OUT_SHA\` ($N_OUT outputs, fallbacks $FB), on \`$BRANCH\` \`$COMMIT\` (\`$DEST/\`: plan, \`outputs.jsonl\`, \`RUN.json\`, raw requests). Trial server with the adapter at scale 0, sha256 checked against the Training 1 manifest; the live server was down only meanwhile and is back as it was (same argv, no adapter listed). Nobody on the PC read the outputs."
log "W8 DONE"
