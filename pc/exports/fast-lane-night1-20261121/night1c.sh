cnt() { tr ' ' '\n' < "$SP/night1-counts.txt" | grep "^$1:" | cut -d: -f2; }   # complete/failed/declared/gpu of a block


# --- the GPU, read only, under the cloud's rule of 22 Nov ~00:35 Berlin (the 00:28 0x20 was the memory, not the core):
#  1. 2 runs at once, in the declared order;  2. 0x20 or 0x40 set for more than 30 minutes in a row at 2 -> 1 run at a time;
#  3. 0x40 at all, or the core above 83 C for 10 minutes -> no new runs for the night, and a post;
#  4. a sample every minute, every fifth to gpu-log.csv; the minutes with 0x20 set, per block, go into the DONE posts;  5. no power or clock change.
GPULOG=$SP/gpu-log.csv
GQ=timestamp,temperature.gpu,temperature.memory,power.draw,fan.speed,utilization.gpu,clocks.sm,clocks_throttle_reasons.active
SLOTSF=$SP/night1-slots; GSTOPF=$SP/night1-gpustop; CURB=$SP/night1-curblock; TH20=$SP/night1-th20.txt
gpost() { printf '%s\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n' "$1" > "$SP/gpu-post.md"; (cd "$REPO" && gh pr comment 1 --repo weltogeisto/hegel-in-delhi --body-file "$SPW/gpu-post.md" 2>&1 | tail -1 >> "$LOG"); }
gpu_logger2() {
  local n=0 hot=0 cont=0 line T R b20 b40
  while true; do
    line=$(nvidia-smi --query-gpu=$GQ --format=csv,noheader 2>/dev/null | head -1)
    T=$(echo "$line" | cut -d, -f2 | tr -dc 0-9); R=$(echo "$line" | awk -F, '{print $NF}' | tr -d ' \r')
    [ $((n % 5)) = 0 ] && echo "$line" >> "$GPULOG"
    if [ "${T:-0}" -gt 83 ]; then hot=$((hot+1)); else hot=0; fi
    b20=0; b40=0; case "$R" in 0x*) [ $(( R & 0x20 )) -ne 0 ] && b20=1; [ $(( R & 0x40 )) -ne 0 ] && b40=1;; esac
    [ $b20 = 1 ] && cat "$CURB" >> "$TH20"
    if [ $b20 = 1 ] || [ $b40 = 1 ]; then cont=$((cont+1)); else cont=0; fi
    if [ ! -e "$GSTOPF" ] && { [ $b40 = 1 ] || [ $hot -ge 10 ]; }; then
      if [ $b40 = 1 ]; then WHY="0x40 (HW thermal slowdown) appeared"; else WHY="the core was above 83 C for $hot minutes"; fi
      echo "$WHY at $(date +%H:%M)" > "$GSTOPF"; echo "$line" >> "$GPULOG"; log "GPU stop: $WHY: $line"
      gpost "**BLOCKED (no new runs tonight), the fast lane night 1, the GPU (PC seat, $(date +%H:%M) Berlin):** $WHY. Sample: \`$line\`. The runs already going finish; the block's DONE follows. No power or clock setting changed."
    fi
    if [ "$(cat "$SLOTSF" 2>/dev/null)" = 2 ] && [ $cont -gt 30 ]; then
      echo 1 > "$SLOTSF"; echo "$line" >> "$GPULOG"; log "GPU: 0x20/0x40 set for $cont minutes in a row at 2 runs: 1 run at a time from now ($line)"
    fi
    n=$((n+1)); sleep 60
  done
}

# --- the scheduler, taking over from night1b.sh: its runs still going are counted (by their process) until their lines reach DONEF
PIDS=(); ABORT=""; STOP=""
start_run() {  # BLOCK NAME DAY ARM SEED
  ( W bash /home/ai/night1/night1_run.sh $2 $3 $4 $5 $1 $(maxsecs) "$WDEST" >> "$SP/night1-runs.log" 2>&1; echo "$2 $?" >> "$DONEF" ) &
  PIDS+=($!); log "start $2 (block $1; $(inflight) running, at most $(cat "$SLOTSF"))"
}
prune() { local a=() p; for p in "${PIDS[@]}"; do kill -0 $p 2>/dev/null && a+=($p); done; PIDS=("${a[@]}"); }
inflight() { prune; local o=0 N P; P=$(ps -ef | grep -o -E 'night1_run.sh (day[0-9]+-[a-z]+-[0-9]+|band-r[12]) ' | awk '{print $2}')
  for N in "${ORPH[@]}"; do grep -q "^$N " "$DONEF" && continue; echo "$P" | grep -qx "$N" && o=$((o+1)); done; echo $(( ${#PIDS[@]} + o )); }
after_done() {
  local n lines N RC
  n=$(wc -l < "$DONEF"); [ $n -gt $SEEN ] || return 0
  lines=$(tail -n +$((SEEN+1)) "$DONEF" | head -n $((n-SEEN))); SEEN=$n
  while read -r N RC; do
    [ -n "$N" ] || continue
    log "done $N rc=$RC"; SINCE=$((SINCE+1))
    [ "$RC" = 0 ] && FAILRUN=0 || FAILRUN=$((FAILRUN+1))
  done <<< "$lines"
  [ -z "$ABORT" ] && ! up && { check8082 "after a run"; ABORT="the live server stopped answering during the night (the Windows starter was tried; see the log)."; }
  if [ -z "$ABORT" ]; then PS=$(W python3 "$WSP/night1_pid.py" 2>&1); [ "$PS" = SAME ] || ABORT="the 8082 server is not the one recorded at the start ($PS)."; fi
  [ -z "$ABORT" ] && [ $FAILRUN -ge 3 ] && ABORT="three runs in a row failed."
  [ $SINCE -ge 9 ] && { commit_push "progress"; SINCE=0; }
  return 0
}
wait_one() { sleep 10; after_done; }
wait_slot() { after_done; while [ $(inflight) -ge $(cat "$SLOTSF" 2>/dev/null || echo 2) ]; do wait_one; done; }
wait_all() { while [ $(inflight) -gt 0 ]; do wait_one; done; after_done; }
run_block() {  # BLOCK: start every line of ORDER in that block not yet started, in order, as slots free up; then wait for all
  local BL N D A S
  echo "$1" > "$CURB"
  while read -r BL N D A S <&3; do
    [ "$BL" = "$1" ] || continue
    echo "$STARTED" | grep -qx "$N" && continue
    wait_slot
    [ -n "$ABORT" ] && break
    [ -e "$GSTOPF" ] && { STOP="the GPU rule stopped new runs for the night ($(cat "$GSTOPF")); $N and later not started"; break; }
    late && { STOP="07:30 reached; $N and later not started"; break; }
    start_run $BL $N $D $A $S
  done 3< "$ORDER"
  wait_all
}
thmin() { grep -c "^$1\$" "$TH20"; }
mode() { local m="runs at once: 3 until $HANDOVER, then 2 (the cloud's 00:35 GPU rule)"; local one; one=$(grep -o -E '^\[[0-9-]+T[0-9:]+\] GPU: 0x20/0x40 set' "$LOG" | head -1 | sed 's/^\[[0-9-]*T\([0-9]*:[0-9]*\).*/\1/'); [ -n "$one" ] && m="$m, then 1 from $one (0x20 over 30 minutes in a row)"; echo "$m"; }
block_post() {  # BLOCK LABEL [EXTRA]
  local c; c=$(cnt $1); IFS=/ read -r OK FAIL DECL GPU <<< "$c"
  local HEAD; HEAD=$(cd "$SP/night1-branch" && git rev-parse --short HEAD)
  post "**DONE, the fast lane night 1, $2 (PC seat, $(date +%H:%M) Berlin), unread, on \`$BRANCH\` (\`$HEAD\`):** **$OK of $DECL runs complete**, $FAIL failed or stopped${STOP:+ ($STOP)}; about $GPU GPU-minutes. Live server never restarted (argv pin $PIN); engine $ENGINE_NOTE. **GPU:** 0x20 (SW thermal slowdown, the memory) set in $(thmin $1) one-minute samples during the block; $(mode).${3:+ $3}"
}

# --- the hand-over (night1b.sh and its GPU logger were stopped just before; its runs still going were left alone)
HANDOVER=$(date +%H:%M)
log "night 1 continued by night1c.sh at $HANDOVER: the cloud's GPU rule (2 runs at once; 1 after 30 minutes of 0x20/0x40; stop on 0x40 or 83 C for 10 minutes)"
