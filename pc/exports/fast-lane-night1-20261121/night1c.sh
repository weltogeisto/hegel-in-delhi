SEEN=$(grep -c -E '\] done [^ ]+ rc=' "$LOG")
SINCE=$(awk '/\] pushed /{s=0} /\] done [^ ]+ rc=/{s++} END{print s+0}' "$LOG")
FAILRUN=$(grep -o -E '\] done [^ ]+ rc=[0-9]+' "$LOG" | awk -F'rc=' '{if ($2==0) f=0; else f++} END{print f+0}')
STARTED=$( { grep -o -E '\] start [^ ]+' "$LOG" | awk '{print $3}'; ps -ef | grep -o -E 'night1_run.sh (day[0-9]+-[a-z]+-[0-9]+|band-r[12]) ' | awk '{print $2}'; } | sort -u)
ORPH=(); for N in $STARTED; do grep -q "^$N " "$DONEF" || ORPH+=($N); done
log "taken over: engine '$ENGINE_NOTE'; pin $PIN; started $(echo "$STARTED" | grep -c .); done lines $SEEN (DONEF $(wc -l < "$DONEF")); still going: ${ORPH[*]}; failures in a row $FAILRUN; since push $SINCE"
[ -n "$ENGINE_NOTE" ] && [ -n "$PIN" ] && [ "$SEEN" -le "$(wc -l < "$DONEF" | tr -dc 0-9)" ] || { log "hand-over state does not add up; stopping"; post "**BLOCKED, the fast lane night 1 (PC seat, $(date +%H:%M) Berlin):** the hand-over to 2 runs at once did not add up (see the log); the runs already going finish, nothing new starts."; exit 1; }
cp "$SP/night1c.sh" "$SP/night1-branch/$DEST/"
gpu_logger2 & GPUPID=$!; log "GPU logger (the 00:35 rule) started"

# --- the blocks
run_block b1
commit_push "block 1"
block_post b1 "block 1 (museums off and on, Days 50-52, 8 seeds)" "Noise band (Day 51, seed 1831, culture off, twice, started together, the third slot filled): $BAND"
if [ -z "$ABORT" ] && [ -z "$STOP" ]; then run_block b2; commit_push "block 2"; block_post b2 "block 2 (culture and HEGEL_FILE_ACT on, Days 51-52, 12 seeds)"; fi
if [ -z "$ABORT" ] && [ -z "$STOP" ]; then run_block b3; commit_push "block 3"; block_post b3 "block 3 (block 1 with 8 more seeds)"; fi
[ -n "$STOP" ] && log "$STOP"

# --- the end
kill $GPUPID 2>/dev/null; GPUSTATS=$(python "$SPW/night1_gpustats.py" "$SPW/gpu-log.csv" 2>&1); log "GPU: $GPUSTATS"
TH="0x20 one-minute samples per block: b1 $(thmin b1), b2 $(thmin b2), b3 $(thmin b3)"
check8082 "after the last run"; c=$?
LIVE="8082 answers after the last run."; [ $c = 2 ] && LIVE="**8082 had stopped answering after the last run; the Windows starter brought it back.**"; [ $c = 1 ] && LIVE="**8082 does not answer after the last run and the Windows starter did not bring it back: it needs a human before 08:59.**"
cp "$LOG" "$SP/night1-branch/$DEST/night1.log"; cp "$SP/night1-runs.log" "$SP/night1-branch/$DEST/night1-runs.log" 2>/dev/null
