HEAD=$(cd "$SP/night1-branch" && git rev-parse --short HEAD)
if [ -n "$ABORT" ]; then
  post "**BLOCKED, the fast lane night 1 (PC seat, $(date +%H:%M) Berlin):** $ABORT The night stopped there. Counts (block:complete/failed/declared/GPU-min): $(cat "$SP/night1-counts.txt"). Pushed to \`$BRANCH\` (\`$HEAD\`). $TH; $(mode). $LIVE"
else
  post "**DONE, the fast lane night 1 (PC seat, $(date +%H:%M) Berlin), unread, on \`$BRANCH\` (\`$HEAD\`):** $T0 to $(date +%H:%M)${STOP:+; $STOP}. Counts (block:complete/failed/declared/GPU-min): $(cat "$SP/night1-counts.txt"). Layout: \`runs/day<N>-<off|on|act>-<seed>/\`, \`runs.jsonl\` in the declared order, \`band/\`, \`ORDER.txt\`, \`MORNINGS.json\`, \`SERVER.json\`, \`gpu-log.csv\`. **GPU** (5-min samples): $GPUSTATS. $TH; $(mode). $LIVE"
fi
log "done"
