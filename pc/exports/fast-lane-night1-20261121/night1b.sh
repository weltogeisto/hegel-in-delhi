GQ=timestamp,temperature.gpu,temperature.memory,power.draw,fan.speed,utilization.gpu,clocks.sm,clocks_throttle_reasons.active
gpost() { printf '%s\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n' "$1" > "$SP/gpu-post.md"; (cd "$REPO" && gh pr comment 1 --repo weltogeisto/hegel-in-delhi --body-file "$SPW/gpu-post.md" 2>&1 | tail -1 >> "$LOG"); }
gpu_logger() {  # pause when the core is above 83 C for more than 10 minutes or a thermal slowdown bit (0x20 SW, 0x40 HW) is set; resume under 80 C
  local n=0 hot=0 paused=0 line T R th
  nvidia-smi --query-gpu=$GQ --format=csv 2>/dev/null | head -1 > "$GPULOG"
  while true; do
    line=$(nvidia-smi --query-gpu=$GQ --format=csv,noheader 2>/dev/null | head -1)
    T=$(echo "$line" | cut -d, -f2 | tr -dc 0-9); R=$(echo "$line" | awk -F, '{print $NF}' | tr -d ' \r')
    [ $((n % 5)) = 0 ] && echo "$line" >> "$GPULOG"
    if [ "${T:-0}" -gt 83 ]; then hot=$((hot+1)); else hot=0; fi
    th=0; case "$R" in 0x*) [ $(( R & 0x60 )) -ne 0 ] && th=1;; esac
    if [ $paused = 0 ] && { [ $hot -gt 10 ] || [ $th = 1 ]; }; then
      touch "$PAUSEF"; paused=1; echo "$line" >> "$GPULOG"; log "GPU pause: $line"
      gpost "**BLOCKED (paused), the fast lane night 1, the GPU (PC seat, $(date +%H:%M) Berlin):** no new runs start until the core is under 80 C. Sample: \`$line\` (core above 83 C for $hot min, thermal bit $th). Running runs finish; no power or clock setting changed."
    fi
    if [ $paused = 1 ] && [ "${T:-99}" -lt 80 ] && [ $th = 0 ]; then
      rm -f "$PAUSEF"; paused=0; log "GPU resume: $line"
      gpost "**DONE, the GPU pause ended (PC seat, $(date +%H:%M) Berlin):** core ${T} C, no thermal bit; new runs start again."
    fi
    n=$((n+1)); sleep 60
  done
}

# --- scheduler: up to SLOTS runs at once; completions are lines "NAME RC" in DONEF
PIDS=(); SEEN=0; ABORT=""; FAILRUN=0; BANDDONE=0; SINCE=0
start_run() {  # BLOCK NAME DAY ARM SEED
  local DD=$WDEST; [ "$1" = band ] && DD=$WDEST/band
  ( W bash /home/ai/night1/night1_run.sh $2 $3 $4 $5 $1 $(maxsecs) "$DD" >> "$SP/night1-runs.log" 2>&1; echo "$2 $?" >> "$DONEF" ) &
  PIDS+=($!); log "start $2 (block $1; ${#PIDS[@]} running)"
}
prune() { local a=() p; for p in "${PIDS[@]}"; do kill -0 $p 2>/dev/null && a+=($p); done; PIDS=("${a[@]}"); }
after_done() {
  local n lines line N RC
  n=$(wc -l < "$DONEF"); [ $n -gt $SEEN ] || return 0
  lines=$(tail -n +$((SEEN+1)) "$DONEF" | head -n $((n-SEEN))); SEEN=$n
  while read -r N RC; do
    [ -n "$N" ] || continue
    log "done $N rc=$RC"; SINCE=$((SINCE+1))
    [ "$RC" = 0 ] && FAILRUN=0 || FAILRUN=$((FAILRUN+1))
  done <<< "$lines"
  [ -z "$ABORT" ] && ! up && { check8082 "after a run"; ABORT="the live server stopped answering during the night (the Windows starter was tried; see the log)."; }
  if [ -z "$ABORT" ]; then PS=$(W python3 "$WSP/night1_pid.py" 2>&1); [ "$PS" = SAME ] || ABORT="the 8082 server is not the one recorded at the start ($PS)."; fi
  [ -z "$ABORT" ] && [ $FAILRUN -ge 3 ] && ABORT="three runs in a row failed."
  if [ $BANDDONE = 0 ] && grep -q '^band-r1 ' "$DONEF" && grep -q '^band-r2 ' "$DONEF"; then
    BANDDONE=1; BAND=$(W bash "$WSP/night1_band.sh" "$WDEST" 2>&1 | tr '\n' ' '); log "band: $BAND"; commit_push "the noise band"; SINCE=0
  fi
  [ $SINCE -ge 9 ] && { commit_push "progress"; SINCE=0; }
  return 0
}
wait_one() { wait -n 2>/dev/null || sleep 5; prune; after_done; }
wait_slot() { prune; after_done; while [ ${#PIDS[@]} -ge $SLOTS ]; do wait_one; done
  [ -e "$PAUSEF" ] && log "waiting: the GPU is hot"; while [ -e "$PAUSEF" ]; do sleep 30; prune; after_done; done; }
wait_all() { prune; while [ ${#PIDS[@]} -gt 0 ]; do wait_one; done; after_done; }
run_block() {  # BLOCKS... : start every line of ORDER whose block is listed, in order, as slots free up; then wait for all
  local BL N D A S
  while read -r BL N D A S <&3; do
    [[ " $* " == *" $BL "* ]] || continue
    wait_slot
    [ -n "$ABORT" ] && break
    late && { STOP="07:30 reached; $N and later not started"; break; }
    start_run $BL $N $D $A $S
  done 3< "$ORDER"
  wait_all
}
